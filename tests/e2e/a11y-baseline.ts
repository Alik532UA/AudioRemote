/**
 * БОРГ ДОСТУПНОСТІ — ЧИСЛОМ, ЯКЕ ЛИШЕ СПАДАЄ (ACCESSIBILITY-v9 § 10.1.1,
 * `A11Y-AXE-BASELINE`).
 *
 * ## Чому не `toEqual([])` просто в описі
 *
 * Бо це виглядає як найсуворіший можливий гейт, а насправді найкрихкіший.
 * axe-core додає нові правила в МІНОРНИХ версіях, а Dependabot приносить їх
 * щотижня — тобто гейт із літеральним нулем червоніє від оновлення залежності,
 * без жодної зміни коду. Червоний гейт, причина якого не в коді, вимикають, і
 * тоді він не ловить уже нічого.
 *
 * ## Нуль — теж базове число
 *
 * Сьогодні тут скрізь нуль, і записаний він так само, як будь-яке інше число.
 * Різниця не в значенні, а в тому, що при ЗРОСТАННІ порушень опис падає з
 * переліком, а при ЗМЕНШЕННІ — просить оновити базу. Обидва повідомлення
 * адресні, і жодне не спокушає вимкнути перевірку.
 *
 * ## Число окремо, типи окремо
 *
 * `KNOWN` перелічує `id` правил, які вже порушені. Поява НОВОГО типу валить
 * прогін навіть у межах ліміту: інакше виправлення одного порушення тихо
 * звільняло б місце під зовсім інше.
 */

/** Стани, які міряються. Ключ — і назва опису, і колонка в обох переліках. */
