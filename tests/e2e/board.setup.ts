import { expect, test as setup } from '@playwright/test';

/**
 * ЕМУЛЯТОР НА МІСЦІ Й ПРАВИЛА В НЬОМУ ДІЮТЬ.
 *
 * Те саме питання, що й у `identity.setup.ts`, лише про іншу залежність: не
 * «чи той артефакт на порті», а «чи та база». І помилитися тут ще дешевше.
 *
 * ## Чому окремо перевіряється ВІДМОВА в корені
 *
 * Емулятор застосовує правила рівно до однієї бази — тієї, яку створює за
 * `firebase.json`, тобто `{projectId}-default-rtdb`. На будь-яке ІНШЕ імʼя він
 * піднімає порожню базу «дозволити все»: туди проходить навіть запис без
 * автентифікації. Прогін проти такої бази зелений завжди — він просто не
 * перевіряє нічого, і саме на цьому проєкт уже одного разу спіткнувся
 * (див. `.env.development`).
 *
 * Тому ознака тут не «база відповідає», а «база ВІДМОВЛЯЄ читати корінь».
 * `401` доводить, що правила прочитані; `200` означав би, що ми говоримо з
 * порожньою базою без жодних правил.
 *
 * ## Чому окремо перевіряється auth
 *
 * Правила вимагають `auth != null` скрізь, а вхід тут анонімний. Без
 * auth-емулятора сторінка не входить, `connect()` не повертається, і плеєр
 * показує «емулятор не запущено» — тобто описи падають на таймаутах пошуку
 * елементів, а причина не названа ніде. Це трапляється частіше, ніж здається:
 * чужий емулятор на 9020, піднятий із `--only database`, виглядає як робочий.
 */

const DB = process.env.E2E_DB_URL ?? 'http://127.0.0.1:9020';
const AUTH = process.env.E2E_AUTH_URL ?? 'http://127.0.0.1:9119';
const NS = 'demo-audioremote-default-rtdb';

setup('база емулятора відповідає, і правила в ній діють', async ({ request }) => {
	const root = await request.get(`${DB}/.json?ns=${NS}`, { failOnStatusCode: false });

	expect(
		root.status(),
		`база емулятора не відповідає на ${DB} — підніміть її: npm run emulators`
	).not.toBe(0);

	expect(
		root.status(),
		'корінь бази читається — значить правила НЕ діють: емулятор підняв порожню ' +
			`базу «дозволити все» під іншим простором імен, ніж ${NS}`
	).toBe(401);
});

setup('емулятор входу відповідає', async ({ request }) => {
	const answer = await request.get(`${AUTH}/`, { failOnStatusCode: false });

	expect(
		answer.status(),
		`емулятор входу мовчить на ${AUTH}. Найчастіша причина — на 9020 висить ` +
			'емулятор від попереднього прогону, піднятий лише з `--only database`: ' +
			'порт зайнятий, тож новий не стартував, а входу немає'
	).toBeLessThan(500);
});
