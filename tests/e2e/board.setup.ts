import { readFileSync } from 'node:fs';
import { expect, test as setup, type APIRequestContext } from '@playwright/test';
import { createBoard, expectInside, joinAsRemote } from './board';

/**
 * ЕМУЛЯТОР НА МІСЦІ Й ПРАВИЛА В НЬОМУ ДІЮТЬ.
 *
 * Те саме питання, що й у `identity.setup.ts`, лише про іншу залежність: не
 * «чи той артефакт на порті», а «чи та база». І помилитися тут ще дешевше.
 *
 * ## Чому правила ТУТ не перевіряються
 *
 * Спокуса була: прочитати корінь і чекати відмови — мовляв, відмовляє, значить
 * правила прочитані. Перша редакція так і робила й одного разу навіть була
 * зелена. Але REST-доступ до емулятора БЕЗ ТОКЕНА він сам вважає адмінським,
 * тож код відповіді залежить від версії емулятора, а не від правил: свіжий
 * віддав 200 там, де залишений від попереднього прогону віддавав 401.
 *
 * Перевірка, чий вердикт залежить не від того, що вона нібито міряє, гірша за
 * відсутню. Правила має `npm run check:rules` — 61 випадок на живому
 * емуляторі, і саме там їм місце. Тут лишається питання простіше: чи взагалі
 * є з ким говорити.
 *
 * ## Чому окремо перевіряється auth
 *
 * Правила вимагають `auth != null` скрізь, а вхід тут анонімний. Без
 * auth-емулятора сторінка не входить, `connect()` не повертається, і плеєр
 * показує «емулятор не запущено» — тобто описи падають на таймаутах пошуку
 * елементів, а причина не названа ніде. Це трапляється частіше, ніж здається:
 * чужий емулятор на 9020, піднятий із `--only database`, виглядає як робочий.
 *
 * ## Чому тут ще й тотожність ДЕВ-СЕРВЕРА
 *
 * `identity.setup.ts` доводить тотожність лише ОДНОГО з двох серверів набору —
 * того, що віддає `build/`. Дошкова половина ходить у дев-сервер, і про нього
 * не питав ніхто.
 *
 * Заміряно на цій машині: порт 5174 тримав дев-сервер СУСІДНЬОГО проєкту,
 * піднятий уранці. Vite, не діставши 5173, мовчки бере наступний, а
 * `reuseExistingServer` так само мовчки погоджується на те, що вже слухає порт.
 * Далі набір чесно ганяв ЧУЖИЙ застосунок і звітував «немає елемента
 * board-id» — тобто червоніло не те й не про те.
 *
 * Гірший випадок — навпаки зелений: на дев-порті опиняється ЗБІРКА цього ж
 * проєкту. Конфіг Firebase запікається у збірку, тож проби пішли б у справжню
 * базу школи. Тому опис питає і «чи ми це», і «чи це дев».
 *
 * ## Порядок тут навмисний
 *
 * `mode: 'serial'`: перше ж питання, на яке немає відповіді, зупиняє решту.
 * Інакше «дорога до дошки не пройшла» друкувалося б поруч із справжньою
 * причиною й перетягувало б увагу на себе.
 */

setup.describe.configure({ mode: 'serial' });

const DB = process.env.E2E_DB_URL ?? 'http://127.0.0.1:9020';
const AUTH = process.env.E2E_AUTH_URL ?? 'http://127.0.0.1:9119';
const NS = 'demo-audioremote-default-rtdb';

/**
 * Код відповіді або `null`, якщо порт так і не відповів.
 *
 * Дві речі разом. По-перше, `request.get` на мертвий порт КИДАЄ, а не повертає
 * нуль, і тоді прогін показує `ECONNREFUSED 127.0.0.1:9119` замість пояснення,
 * що це означає, — саме таке повідомлення цей файл і покликаний замінити.
 *
 * По-друге, ВІДПОВІДЬ ЧЕКАЄТЬСЯ, а не питається один раз. Обидві перевірки
 * біжать тоді, коли Playwright щойно підняв два сервери, і машина в цю мить
 * зайнята: одноразове питання вже одного разу дало «емулятор мовчить» на
 * живому емуляторі. Перевірка, що стереже від плутанини, сама зробила б
 * висновок навмання.
 */
async function reach(request: APIRequestContext, url: string): Promise<number | null> {
	const until = Date.now() + 30_000;
	for (;;) {
		try {
			return (await request.get(url, { failOnStatusCode: false, timeout: 5000 })).status();
		} catch {
			if (Date.now() > until) return null;
			await new Promise((wake) => setTimeout(wake, 500));
		}
	}
}

setup('база емулятора відповідає', async ({ request }) => {
	const code = await reach(request, `${DB}/.json?ns=${NS}`);

	expect(
		code,
		`база емулятора мовчить на ${DB} — підніміть її: npm run emulators. ` +
			`Простір імен саме ${NS}: на будь-яке інше імʼя емулятор піднімає ` +
			'порожню базу «дозволити все», і прогін проти неї зелений завжди.'
	).not.toBeNull();
});

setup('емулятор входу відповідає', async ({ request }) => {
	const code = await reach(request, `${AUTH}/`);

	expect(
		code,
		`емулятор входу мовчить на ${AUTH}, і правила вимагають входу скрізь. ` +
			'Найчастіша причина: на порті бази висить емулятор від попереднього прогону, ' +
			'піднятий лише з `--only database`. Тоді новий не стартував — порт зайнятий, — ' +
			'а входу немає. Зняти залишок: netstat -ano | findstr :9020, потім taskkill /PID <pid> /F'
	).not.toBeNull();
});

setup('на дев-порті саме цей проєкт, і саме дев', async ({ request }) => {
	/*
	 * Дві ознаки, і кожна відповідає на своє питання.
	 *
	 * `application-name` лежить літералом у `src/app.html`, тобто його віддає й
	 * дев-сервер, і збірка: це відповідь на «чи наш це застосунок». Версія з
	 * `static/app-version.json` звужує до «чи цей клон» — сусідній проєкт із
	 * того ж канону має такий самий файл, лише з іншим числом.
	 *
	 * А `<meta http-equiv="content-security-policy">` зʼявляється лише у
	 * ЗІБРАНОМУ HTML. Його наявність тут означала б, що дошкові описи зараз
	 * підуть у базу, прописану в збірці, — тобто в справжню базу школи.
	 */
	const page = await request.get('./');
	expect(page.ok(), 'дев-порт не віддає сторінку — сервер не піднявся').toBeTruthy();

	const html = await page.text();
	expect(
		html,
		'на дев-порті ЧУЖИЙ застосунок. Vite, не діставши свого порту, мовчки бере ' +
			'наступний, а набір так само мовчки переймає те, що вже слухає порт. ' +
			'Зняти залишок: netstat -ano | findstr :5194, потім taskkill /PID <pid> /F'
	).toContain('name="application-name" content="AudioRemote"');

	expect(
		/<meta[^>]+http-equiv="content-security-policy"/i.test(html),
		'на дев-порті ЗБІРКА, а не дев-сервер: конфіг Firebase у ній запечений, ' +
			'тож проби пішли б у справжню базу школи, а не в емулятор'
	).toBe(false);

	const stamp = await request.get('./app-version.json');
	expect(stamp.ok(), 'дев-порт не віддає app-version.json — це не наш клон').toBeTruthy();

	const pkg = JSON.parse(readFileSync('package.json', 'utf8')) as { version: string };
	const served = (await stamp.json()) as { version: string };
	expect(served.version, 'на дев-порті інший клон цього ж проєкту').toBe(pkg.version);
});

setup('дев-сервер не зіпсутий збіркою', async ({ page }) => {
	/*
	 * ОКРЕМЕ ПИТАННЯ ВІД «ЧИ НАШ ЦЕ СЕРВЕР»: сервер може бути наш і при цьому
	 * не віддавати застосунок.
	 *
	 * Дев-сервер, що працював ДО `npm run build`, псується: збірка
	 * перегенеровує `.svelte-kit`, і модулі, на які він щойно посилався,
	 * зникають. HTML при цьому віддається як завжди — ламається лише
	 * динамічний імпорт, і побачити це можна тільки в консолі браузера.
	 *
	 * Ціну заміряно двічі. Без цього опису прогрів вичерпував усі три спроби й
	 * падав через дві з половиною хвилини з «дорога до дошки не пройшла» —
	 * повідомленням, яке відправляє шукати поломку в застосунку. Тут те саме
	 * видно за секунди й названо причиною.
	 */
	const broken: string[] = [];
	page.on('console', (message) => {
		if (/failed to fetch dynamically imported module/i.test(message.text())) {
			broken.push(message.text());
		}
	});
	page.on('pageerror', (error) => broken.push(String(error)));

	await page.goto('./menu');

	await expect(
		page.getByTestId('go-create'),
		'дев-сервер віддає сторінку, але застосунок не вантажиться. Найчастіша ' +
			'причина: сервер підняли ДО `npm run build`, і збірка перегенерувала ' +
			'`.svelte-kit` під ним. Лікується перезапуском сервера'
	).toBeVisible({ timeout: 30_000 });

	expect(broken, `застосунок скаржиться на власні модулі:\n${broken.join('\n')}`).toEqual([]);
});

setup('дорога до дошки вже прогріта', async ({ browser }) => {
	/*
	 * ПЕРШИЙ ПРОХІД ПО ХОЛОДНОМУ ЕМУЛЯТОРУ НЕ ВСТИГАЄ — І ЦЕ НЕ ПОЛОМКА.
	 *
	 * `boardExists` має власну межу в десять секунд, а перший анонімний вхід на
	 * щойно піднятому auth разом із першим зʼєднанням до бази в неї не
	 * вкладається. Пульт лишається на сторінці входу, другий раз заходить за
	 * секунду. Заміряно: падав саме ПЕРШИЙ опис дошкової половини, приблизно
	 * три повні прогони з чотирьох, а решта описів проходили завжди.
	 *
	 * Тому тут не одна спроба, а кілька. Це не «поки не пощастить»: кожна
	 * спроба однаково гріє дорогу, а червоніє крок лише тоді, коли не вийшло
	 * ЖОДНОГО разу — тобто коли шлях справді зламаний, і сказати про це одним
	 * зрозумілим рядком краще, ніж пʼятьма описами про присутність.
	 *
	 * Опису для самого плавання тут не треба: описи нижче міряють уже прогріту
	 * дорогу, і якщо котрийсь із них упаде, це буде про застосунок.
	 */
	const ATTEMPTS = 3;
	let last: unknown = null;

	for (let attempt = 1; attempt <= ATTEMPTS; attempt++) {
		const board = await browser.newContext();
		const guest = await browser.newContext();
		try {
			const player = await board.newPage();
			const remote = await guest.newPage();
			const id = await createBoard(player, 'Прогрів');
			await joinAsRemote(remote, id);
			await expectInside(remote);
			last = null;
			break;
		} catch (error) {
			last = error;
		} finally {
			await board.close();
			await guest.close();
		}
	}

	expect(
		last,
		`дорога до дошки не пройшла ${ATTEMPTS} рази поспіль — це вже не холодний ` +
			'старт. Далі всі дошкові описи падатимуть на присутності, тож причина тут'
	).toBeNull();
});
