import { expect, type Page } from '@playwright/test';

/**
 * СТОРІНКИ, ЯКІ ОБХОДИТЬ НАБІР, — ОДНИМ ПЕРЕЛІКОМ.
 *
 * Три описи ходять по тих самих адресах (axe, геометрія, локатори), і три копії
 * переліку розійшлися б мовчки: новий маршрут додали б в одну, і дві інші
 * лишилися б зеленими, не подивившись на нього. Файл навмисно без суфікса
 * `.spec`/`.setup`, тож жоден раннер не візьме його за перевірку — так само, як
 * `board.ts`.
 */

/**
 * Ключ — стан у переліку боргу axe (`a11y-baseline.ts`), значення — адреса.
 *
 * Плеєр і пульт тут БЕЗ ДОШКИ, і це теж стан застосунку — саме той, у якому
 * людина опиняється, відкривши збережене посилання наступного дня.
 */
export const PAGES = {
	root: './',
	menu: './menu',
	create: './create',
	connect: './connect',
	settings: './settings',
	player: './player',
	remote: './remote',
	// Другий вид дошки — так само БЕЗ дошки: обидва екрани мусять чесно
	// відправити в меню, а не впасти.
	info: './info',
	infoRemote: './info-remote',
	// Службова сторінка, якої немає в меню: її дають посиланням тому, хто
	// згодився потикати застосунок. Кнопок на ній більше, ніж на будь-якій
	// іншій, тож обхід доступності потрібен їй не менше за решту.
	beta: './beta-test-checklists'
} as const;

/** Ті самі адреси списком — для описів, яким назви станів не потрібні. */
export const ROUTES: readonly string[] = Object.values(PAGES);

/**
 * СКІЛЬКИ ЧЕКАТИ НА ТЕ, ЩО СТОРІНКА НАМАЛЮВАЛАСЯ.
 *
 * Типові пʼять секунд Playwright тут замалі, і не через застосунок: описи
 * артефактної половини біжать ОДНОЧАСНО з проєктом `emulator`, який у ці ж
 * секунди піднімає java-емулятор, компілює дев-сервер і відкриває два
 * контексти браузера. Заміряно: на зайнятій машині `main` не встигав
 * зʼявитися за пʼять секунд, і падали описи, які про завантаження взагалі не
 * питають.
 *
 * Довше очікування нічого не послаблює: сторінка, яка не малюється, не
 * намалюється ні за пʼять секунд, ні за двадцять. А плаваючий гейт гірший за
 * відсутній — те саме рішення й з тієї ж причини, що `ACROSS` у `board.ts`.
 */
export const RENDERED = { timeout: 20_000 };

/**
 * СКІЛЬКИ ЧЕКАТИ НА ВЕСЬ ОБХІД — тобто межа опису, а не окремого очікування.
 *
 * Типові тридцять секунд Playwright розраховані на опис, який відкриває одну
 * сторінку. Тут їх сім, а в описі axe до кожної ще й приїжджає ядро перевірки
 * й проходить усе дерево доступності. Поодинці це секунда на сторінку; поруч
 * із проєктом `emulator` — заміряно тридцять п'ять секунд на обхід, тобто
 * падіння за межею часу на роботі, яка йде правильно.
 *
 * Більша межа тут нічого не ховає: обхід, що не дійшов до кінця, не дійде ні
 * за тридцять секунд, ні за дві хвилини, а падіння за часом читається як
 * зламаний набір.
 */
export const WALK = 120_000;

/**
 * ЩО ВВАЖАЄТЬСЯ ОРГАНОМ КЕРУВАННЯ. Живе поруч із `settled()`, бо саме за ними
 * він і стежить: доки їхня геометрія їде, сторінка ще не намалювалася.
 */
export const INTERACTIVE =
	'button, a[href], input:not([type=hidden]), select, textarea, summary, [role=button], [role=switch]';

/**
 * ДОЧЕКАТИСЯ, ДОКИ РОЗКЛАДКА ПЕРЕСТАНЕ ЇХАТИ.
 *
 * Плеєр, пульт і обидва екрани інфодошки без дошки чесно відправляють у меню, і
 * перехід іде вже в браузері. `main` при цьому стає видимим ДВІЧІ: спершу на
 * сторінці, з якої йдуть, потім на меню — а після переходу меню ще й дописує
 * згори рядок «чому ви тут», який зсуває картки. Вимір, зроблений між цими
 * моментами, застає розкладку на півдорозі: перевірка перекриття бачила
 * `go-create × go-connect: 287×17`, якого на екрані не буває жодної миті.
 *
 * Заміряно перед виправленням: один прогін із трьох, і щоразу на ІНШІЙ
 * сторінці (`./remote`, `./info-remote`, `./player`), а на самому `./menu` —
 * ніколи. Саме така форма й означає гонку, а не розкладку.
 *
 * Чекаємо не «трохи» й не адреси, а того самого, що потім міряємо: усі стилі
 * застосовані, у `main` є бодай один орган керування, і геометрія всіх органів
 * не змінюється три кадри поспіль. Адреси мало — вона встигає застигнути раніше за напис, що зсуває
 * картки; сон на фіксовані мілісекунди на зайнятій машині коротший за перехід,
 * а на вільній витрачається дарма.
 */
export async function settled(page: Page) {
	await expect(page.locator('main')).toBeVisible(RENDERED);
	await page.waitForFunction(
		(selector) => {
			const seen = window as unknown as { __boxes?: string; __still?: number };
			/*
			 * СТИЛІ МАРШРУТУ ПРИЇЖДЖАЮТЬ ОКРЕМИМ ФАЙЛОМ, і поки він у дорозі,
			 * розмітка вже є, а розкладки ще немає.
			 *
			 * Заміряно на зібраному сайті: під час переходу з `./info` у меню
			 * стилів застосовано 10 з 11, потім 11 з 12, і лише коли всі 12 —
			 * картка стає 358×180. До того вона 287×17, тобто рівно те число, яке
			 * гейт і показував. `link` без `.sheet` — це стиль, який ще не
			 * застосовано; чекати на нього точніше, ніж на будь-яку кількість
			 * кадрів.
			 */
			const styles = [...document.querySelectorAll<HTMLLinkElement>('link[rel=stylesheet]')];
			if (styles.some((link) => link.sheet === null)) return false;

			const main = document.querySelector('main');
			const controls = main ? [...main.querySelectorAll<HTMLElement>(selector)] : [];
			/*
			 * Порожній `main` — це ОБОЛОНКА сторінки, з якої йдуть: шапка вже
			 * намальована, вміст ще ні. Заміряно: на `./player` таких кадрів
			 * два-три поспіль, тобто «геометрія не міняється» справджується на
			 * стані, у якому міряти нема чого.
			 */
			if (controls.length === 0) return false;
			const now = controls
				.map((element) => {
					const box = element.getBoundingClientRect();
					return [box.x, box.y, box.width, box.height].map(Math.round).join(',');
				})
				.join('|');
			if (seen.__boxes !== now) {
				seen.__boxes = now;
				seen.__still = 0;
				return false;
			}
			seen.__still = (seen.__still ?? 0) + 1;
			return seen.__still >= 3;
		},
		INTERACTIVE,
		{ timeout: 10_000 }
	);
}
