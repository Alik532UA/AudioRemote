// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { execFileSync } from 'node:child_process';

/**
 * Індекс і робоче дерево читають ОДИН І ТОЙ САМИЙ текст
 * (AI-AGENT-PITFALLS-v9 § 1.5, `PIT-EOL-GATE`, HIGH).
 *
 * **Чому цього мало — мати `.gitattributes`.** Файл у проєкті вже є, з довгим
 * поясненням, і він задає `* text=auto eol=lf`. Але атрибут діє на ВИДАЧУ:
 * git застосовує його, коли записує файл у робоче дерево. На вже викладені
 * файли він не діє ніколи — зміна `.gitattributes` не переписує жодного з них.
 * Тобто дерево, викладене до появи правила, лишається з CRLF назавжди, а
 * документ поруч стверджує протилежне.
 *
 * ТУТ ЦЬОГО НЕ БУЛО, І ЦЕ ТЕЖ ЗАМІР. На момент постановки гейта
 * `git ls-files --eol` показував 131 текстовий запис, усі `i/lf w/lf`, і жодного
 * двійкового з текстовим атрибутом: `.gitattributes` тут з'явився раніше за
 * перші файли, тож дерево не встигло набрати CRLF. Гейт від того не зайвий —
 * він стереже наступний файл, доданий на машині з іншими налаштуваннями git,
 * і саме його в іншому проєкті пакета додавали вже по 162 зіпсованих файлах.
 *
 * **Чому це дорого.** Гейтів, які читають власні джерела ТЕКСТОМ, тут
 * більшість: `css-tokens`, `icon-imports`, `state-boundary`, `unused`,
 * `devices`, а хеш інлайн-скрипта в CSP рахує `svelte.config.js`. Різниця в
 * один символ на рядок означає інший вердикт, і найгірший прояв — не червоний
 * тест, а мовчазний нуль: регулярка з `$` без прапорця `m` перестає збігатися
 * через `\r`, гейт звітує «нічого не знайдено» й виглядає зеленим.
 *
 * **Що саме перевіряється — стан, а не наявність файлу.** `git ls-files --eol`
 * віддає пару: `i/` — як лежить в індексі (тобто що побачить CI), `w/` — як
 * лежить на диску (тобто що бачить локальний прогін). Розбіжність у цій парі й
 * означає «дві машини читають різне».
 *
 * **Як лікується розбіжність.** Історію чіпати не треба — блоби вже LF, і
 * `git diff` на CRLF-дереві мовчить саме тому. Переписати треба робоче дерево,
 * і робить це звичайне відновлення з індексу: перелік бере сам гейт зі свого
 * повідомлення про падіння.
 *
 * ```bash
 * git checkout -- <файли з переліку>   # на ЧИСТОМУ дереві
 * ```
 *
 * Зворотний експеримент (§ 1.1) виконано двічі. Перед нормалізацією дерева
 * гейт падав із переліком тих самих 162 файлів; після — зелений. Окремо
 * перевірено сам рецепт: `tsconfig.json`, повернутий у CRLF руками, після
 * `git checkout --` знову `w/lf`. На Linux-раннері `actions/checkout` викладає
 * LF, тож там гейт зелений із першого прогону — і саме тому він мусить
 * виконуватися локально, а не «десь у CI».
 */

/**
 * Рядок `git ls-files --eol`: `i/lf    w/crlf  attr/text=auto eol=lf \tшлях`.
 *
 * Шлях відділений ТАБУЛЯЦІЄЮ, а не пробілами: у значенні `attr/` пробіли є
 * (`text=auto eol=lf`), тож розбір по пробілах з'їв би половину атрибута й
 * приклеїв би її до імені файлу.
 */
const ROW = /^i\/(\S+)\s+w\/(\S+)\s+attr\/([^\t]*)\t(.+)$/;

interface Entry {
	/** Як файл лежить в індексі — те, що прочитає CI. */
	index: string;
	/** Як файл лежить на диску — те, що прочитає локальний прогін. */
	work: string;
	/**
	 * Що про файл каже `.gitattributes`: `text=auto eol=lf`, `text eol=crlf`,
	 * `-text`. Доти це поле розбиралося й ВИКИДАЛОСЯ, і разом із ним зникали
	 * дві речі, без яких гейт міряє не те: оголошений виняток `eol=crlf` і сам
	 * факт «файл оголошений текстовим».
	 */
	attr: string;
	path: string;
}

/**
 * Чи оголошений файл ТЕКСТОВИМ у `.gitattributes`.
 *
 * `-text` сюди не підпадає: перед словом стоїть дефіс, а не початок рядка чи
 * пробіл. Саме на цій різниці й тримається перевірка «оголошений текстовим,
 * а виявився двійковим» нижче.
 */
const declaredText = (attr: string): boolean => /(^|\s)text(=|\s|$)/.test(attr);

/** Оголошене закінчення рядка (`eol=crlf`), якщо воно назване поіменно. */
const declaredEol = (attr: string): string | null => /(^|\s)eol=(\S+)/.exec(attr)?.[2] ?? null;

/**
 * ЧЕРВОНИЙ ГЕЙТ МУСИТЬ КАЗАТИ, ЩО САМЕ СТАЛОСЯ.
 *
 * `execFileSync` на ненульовому коді кидає рівно «Command failed: git ls-files
 * --eol» — без `stderr`, без коду виходу, без теки. Прочитати це можна лише
 * як «закінчення рядків зламані», тобто як саме те, що гейт мав би знайти, і
 * шукати починають не там. Заміряно: один прогін із тридцяти на цій машині
 * падає саме так, а наступний — зелений.
 *
 * Друга спроба закриває рівно один клас причин — невдалий ЗАПУСК процесу
 * (на Windows це антивірус або вичерпані дескриптори, коли тридцять воркерів
 * стартують разом). Маскування тут немає за побудовою: вердикт гейта дає
 * ВИВІД git, а не факт запуску, тож «дерево з CRLF» валить обидві спроби
 * однаково. А от «не репозиторій» чи «git не встановлено» тепер приїжджає
 * власними словами git замість здогадки.
 */
function gitLsFiles(): string {
	/*
	 * `execFileSync` без `shell`: ім'я файлу з пробілом чи лапкою в оболонці
	 * розсипалося б, а перевірка про це не сказала б нічого.
	 *
	 * Буфер піднятий явно — типового 1 МБ на нинішнє дерево вистачає, але межа,
	 * яку колись перетне його зростання, дала б обрізаний вивід, тобто
	 * мовчазний нуль знахідок у хвості переліку.
	 */
	const run = () =>
		execFileSync('git', ['ls-files', '--eol'], {
			encoding: 'utf8',
			maxBuffer: 32 * 1024 * 1024
		});

	try {
		return run();
	} catch {
		try {
			return run();
		} catch (error) {
			const fail = error as { status?: number; stderr?: string | Buffer; message?: string };
			throw new Error(
				`git ls-files --eol не віддав переліку (двічі поспіль).\n` +
					`Тека: ${process.cwd()}\n` +
					`Код виходу: ${fail.status ?? '—'}\n` +
					`git сказав: ${String(fail.stderr ?? '').trim() || '(мовчки)'}\n` +
					`Це НЕ вердикт про закінчення рядків: до них черга не дійшла.`,
				// Причина чіпляється навмисно: зведений текст читає людина, а стек
				// початкової помилки лишається тому, хто розбиратиметься глибше.
				{ cause: error }
			);
		}
	}
}

function trackedFiles(): Entry[] {
	const out = gitLsFiles();

	const entries: Entry[] = [];
	for (const line of out.split('\n')) {
		const match = ROW.exec(line.replace(/\r$/, ''));
		if (match)
			entries.push({
				index: match[1],
				work: match[2],
				attr: match[3].trim(),
				path: match[4]
			});
	}
	return entries;
}

const entries = trackedFiles();

/**
 * ЯК git ПОЗНАЧАЄ ДВІЙКОВЕ — `-text`, а НЕ `-`.
 *
 * Доти тут стояло `e.index !== '-'`, і рядка `-` у виводі `git ls-files --eol`
 * не буває взагалі: на цьому дереві 23 записи мають `i/-text w/-text`, і
 * жоден — `i/-`. Тобто фільтр не відсіював нічого, і двійкові файли їхали в
 * перевірки разом із текстовими.
 *
 * Мовчав він тому, що `-text` дорівнює `-text`: пара збігалася, і перевірка
 * розбіжності бачила згоду. Саме так сюди й проліз `rebuild-exe.bat`, у якому
 * замість зворотного слеша лежав самотній `\r` — через нього git вважав
 * пакетний файл двійковим, а гейт вважав це нормою.
 *
 * Обидва написання лишаються в переліку: вердикт гейта не мусить залежати від
 * того, чи змінить git колись формат виводу.
 */
const BINARY = new Set(['-text', '-']);

/** Те, що git вважає двійковим, — байт у байт, закінчень рядків тут немає. */
const binary = entries.filter((e) => BINARY.has(e.index) || BINARY.has(e.work));

const text = entries.filter((e) => !BINARY.has(e.index) && !BINARY.has(e.work));

/**
 * Яким МУСИТЬ бути закінчення рядка в робочому дереві за атрибутами.
 *
 * Для майже всього це `i/lf w/lf`. Але `.gitattributes` називає поіменно один
 * виняток — `*.bat text eol=crlf`, — і для нього ПРАВИЛЬНИЙ стан це саме
 * розбіжність: `i/lf w/crlf`. Доти перевірка цього не знала, бо жодного
 * текстового `.bat` у дереві не було (єдиний був зіпсований і вважався
 * двійковим), тож виняток не виконувався жодного разу. Полагоджений файл
 * зробив би гейт червоним, а порада в повідомленні («git reset --hard»)
 * повернула б рівно той самий стан.
 */
function expectedWork(entry: Entry): string {
	// `none` — файл без жодного закінчення рядка; переписувати в ньому нічого.
	if (entry.index === 'none') return 'none';
	return declaredEol(entry.attr) === 'crlf' ? 'crlf' : entry.index;
}

describe('закінчення рядків (AI-AGENT-PITFALLS-v9 § 1.5)', () => {
	it('перевірка жива: git віддав перелік відстежуваних файлів', () => {
		/*
		 * Межа не нуль: `git ls-files` за межами репозиторію падає, а от
		 * запущений із підкаталогу віддає ЧАСТИНУ дерева — і тоді перевірка
		 * зелена з тієї самої причини, з якої вона й існує.
		 *
		 * 80 — із запасом від заміряних 131 текстового запису на момент коміту.
		 * Число не звіряється на рівність навмисно: гейт, що червоніє від кожного
		 * доданого файлу, вимикають (§ 1.1).
		 */
		expect(text.length, 'git ls-files не віддав дерево — перевіряти нема що').toBeGreaterThan(80);
	});

	it('перевірка жива: у переліку є і .svelte, і .ts', () => {
		const kinds = ['.svelte', '.ts'].filter((ext) => text.some((e) => e.path.endsWith(ext)));
		expect(kinds, 'у переліку немає джерел проєкту — розбір рядка зламався').toEqual([
			'.svelte',
			'.ts'
		]);
	});

	it('в індексі немає CRLF — інакше CRLF поїде в CI', () => {
		const committed = text.filter((e) => e.index === 'crlf' || e.index === 'mixed');
		expect(
			committed.map((e) => `${e.path} (i/${e.index})`),
			'у git закомічено CRLF: `.gitattributes` не діяв на момент додавання цих файлів'
		).toEqual([]);
	});

	it('робоче дерево не розійшлося з індексом', () => {
		/*
		 * `none` — файл без жодного закінчення рядка (однорядкові `.svg`).
		 * Пара `i/none w/none` розбіжністю не є, і вимагати від неї `lf` було б
		 * вимогою дописати порожній рядок у півтори сотні прапорів.
		 *
		 * Звіряємося з `expectedWork`, а не з `e.index`: для `eol=crlf`
		 * розбіжність і є правильним станом.
		 */
		const drift = text.filter((e) => e.work !== expectedWork(e));
		expect(
			drift.map((e) => `${e.path}: i/${e.index} проти w/${e.work} (attr: ${e.attr || '—'})`),
			'локальний прогін читає інший текст, ніж CI. Полагодити на ЧИСТОМУ дереві:\n' +
				'  git rm --cached -r . && git reset --hard'
		).toEqual([]);
	});

	it('оголошений текстовим — і справді текстовий', () => {
		/*
		 * НАЙТИХІШИЙ ІЗ ТРЬОХ ДЕФЕКТІВ, і єдиний, який уже стався.
		 *
		 * git вирішує «текст чи двійкове» ЗА ВМІСТОМ, а не за атрибутом:
		 * побачив NUL або самотній `\r` — і файл стає `-text`, хоч
		 * `.gitattributes` називає його текстовим. Після цього з ним не працює
		 * нічого з того, заради чого атрибут і ставили: ні нормалізація
		 * закінчень рядків, ні `--renormalize`, ні показ у `git diff`.
		 *
		 * Саме це й було з `rebuild-exe.bat`: замість `scripts\rebuild-exe.mjs`
		 * у ньому лежало `scripts` + самотній `\r` + `ebuild-exe.mjs`, тобто
		 * шлях до неіснуючого файлу. «Перезбірка одним кліком» не працювала з
		 * дня появи, і жодна перевірка цього не бачила: гейт вважав файл
		 * двійковим, а `git diff` на двійковому мовчить.
		 *
		 * Ознака рівно одна й дешева: атрибут каже `text`, а git каже `-text`.
		 * Інших причин у цієї пари немає — або у файлі сміття, або атрибут
		 * поставлений не тому файлу (тоді його треба назвати двійковим у
		 * `.gitattributes`, як зроблено для `*.icns`).
		 */
		const mislabelled = binary.filter((e) => declaredText(e.attr));
		expect(
			mislabelled.map((e) => `${e.path} (attr: ${e.attr})`),
			'git вважає ці файли ДВІЙКОВИМИ, хоч .gitattributes оголошує їх текстовими.\n' +
				'Або у файлі керуючий символ (найчастіше самотній \\r замість \\\\), або\n' +
				'він двійковий і має бути названий таким у .gitattributes.\n' +
				'Подивитися: git ls-files --eol -- <шлях>'
		).toEqual([]);
	});
});
