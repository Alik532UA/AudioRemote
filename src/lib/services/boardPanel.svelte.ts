import type { Snippet } from 'svelte';

/**
 * ШАПКА ДОШКИ ЗА КНОПКОЮ НАЛАШТУВАНЬ — на телефоні.
 *
 * Назву дошки, ідентифікатор і стан звʼязку читають раз на вечір, а місце
 * карткою вони займали завжди — і саме те місце, яке на телефоні потрібне
 * спискові. Тому на вузькому екрані вони переїжджають під шестірню, разом із
 * переходом до справжніх налаштувань застосунку.
 *
 * Сторінка кладе сюди свій фрагмент, розкладка його малює. Через сховище, а
 * не через властивість, бо між ними стоїть `+layout.svelte`, який про дошку не
 * знає нічого й знати не мусить.
 *
 * Класти сюди ЛИШЕ з `$effect`, який прибирає за собою: інакше фрагмент
 * пережив би сторінку, і під шестірнею лишилася б дошка, з якої вже пішли.
 */
class BoardPanel {
	content = $state<Snippet | null>(null);
}

export const boardPanel = new BoardPanel();
