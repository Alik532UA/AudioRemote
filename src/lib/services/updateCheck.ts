/**
 * КОЛИ ПИТАТИ СЕРВЕР, ЧИ Є НОВА ВЕРСІЯ.
 *
 * ## Чого бракувало
 *
 * Воркер реєструвався, пропозиція оновитися була готова — і не з'являлася
 * ніколи. Браузер перевіряє воркер сам лише на НАВІГАЦІЇ, а приймач відкривають
 * зранку й не чіпають до вечора: жодної навігації за весь день. Тобто новий код
 * виїжджав у прод, а в залі грала збірка тижневої давнини, і дізнатися про це не
 * було звідки.
 *
 * Тут живе рішення «час питати чи ні». Саме запитування — один рядок
 * (`registration.update()`); складне тут інше — не спитати зайвий раз.
 *
 * ## Чому не просто `setInterval`
 *
 * Бо крім таймера є повернення до вкладки, і воно важливіше: людина відкриває
 * приймач перед заняттям саме тоді, коли оновлення й треба забрати. Але
 * повернення піднімає ДВІ події — `visibilitychange` і `focus`, — тож без
 * спільного проміжку одне переключення вікна дає два запити поспіль.
 *
 * ## Чого тут немає навмисно
 *
 * Примусового оновлення. Ні «мінімальної версії», ні тихого перезавантаження:
 * вкладка приймача — єдине, що грає звук у залі, і обривати відтворення
 * застосунок не має права навіть заради себе. Рішення лишається за людиною —
 * тому це `updateCheck`, а не `updateApply`.
 */

/** Як часто питати, поки вкладку не чіпають. */
export const CHECK_EVERY_MS = 30 * 60 * 1000;

/**
 * Найменший проміжок між двома запитами.
 *
 * Не оптимізація: без нього повернення до вкладки б'є двома запитами підряд,
 * бо `visibilitychange` і `focus` приходять обидва.
 */
export const MIN_GAP_MS = 60 * 1000;

export interface UpdateHost {
	now(): number;
	/** Офлайн — не привід питати: відповіді все одно не буде. */
	online(): boolean;
	/** Власне запит до сервера: у житті це `registration.update()`. */
	update(): void;
}

export interface UpdateSchedule {
	/** Спробувати спитати. Повертає, чи справді пішли. */
	tick(): boolean;
}

export function createUpdateSchedule(host: UpdateHost): UpdateSchedule {
	/*
	 * `null`, а НЕ `0`, і це не смак.
	 *
	 * Тут стояло `let lastAt = 0` з умовою `lastAt !== 0 && …`, тобто нуль
	 * означав «ще не питали». Але нуль — це ще й дійсна мітка часу, тож якщо
	 * перший запит випадав рівно на неї, наступний тік не бачив проміжку й
	 * ішов одразу — саме той подвійний запит, проти якого проміжок і стоїть.
	 *
	 * У житті `Date.now()` нуля не віддає, тож вада латентна. Знайшлася вона
	 * у сусідньому `HotPaste`, коли той самий модуль там уперше накрили
	 * перевіркою з часом від нуля.
	 */
	let lastAt: number | null = null;

	return {
		tick() {
			if (!host.online()) return false;

			const now = host.now();
			if (lastAt !== null && now - lastAt < MIN_GAP_MS) return false;

			lastAt = now;
			host.update();
			return true;
		}
	};
}
