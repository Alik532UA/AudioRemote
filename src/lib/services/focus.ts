/**
 * ПАЛЕЦЬ НЕ ЛИШАЄ ПО СОБІ РАМКИ.
 *
 * Після натискання кнопка лишалася у фокусі, і рамка навколо неї стояла доти,
 * доки не торкнешся чогось іншого, — зокрема й після того, як трек відзвучав.
 * Читалося це як «оцей трек зараз обраний», тобто як брехня.
 *
 * Знімається фокус ЛИШЕ для натискання вказівником: `detail` у події кліку — це
 * кількість натискань, і з клавіатури (Enter, пробіл) там нуль. Забрати фокус
 * там означало б викинути людину з місця в списку на кожному запуску.
 */
export function releaseAfterTap(event: MouseEvent): void {
	if (event.detail > 0 && event.currentTarget instanceof HTMLElement) {
		event.currentTarget.blur();
	}
}
