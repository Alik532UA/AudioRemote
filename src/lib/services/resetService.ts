import { base } from '$app/paths';
import { clearOwn } from './storage';
import { deleteOwnCaches, unregisterOwnServiceWorkers } from './ownScope';

/**
 * АВАРІЙНЕ СКИДАННЯ — вихід із стану, з якого інакше виходу немає.
 *
 * ## Чого бракувало
 *
 * Оновлення сторінки тут повністю віддане workbox: новий воркер стає в
 * `waiting`, людина натискає «оновити». Поки все справне, цього досить. Але
 * шляху НАЗАД не існувало: якщо в кеші опинилася побита збірка, або воркер
 * застряг, або зіпсувалися налаштування, застосунок відкривався зламаним і
 * відкривався так щоразу.
 *
 * Єдиним виходом лишалося «очистити дані сайту» в налаштуваннях браузера. Для
 * людини за плеєром у школі це не вихід узагалі: меню закопане, називається
 * незрозуміло, а на спільному origin воно ще й витирає сусідні проєкти автора.
 *
 * ## Порядок кроків має значення
 *
 * Спершу зняти воркер, потім кеші. Навпаки — воркер живий і може закешувати
 * заново те саме, поки триває прибирання.
 *
 * Перезавантаження — останнім, і з обхідним параметром: без нього браузер
 * віддасть оболонку зі СВОГО HTTP-кеша, тобто рівно те, від чого щойно
 * позбулися. `location.replace`, а не `href`: поламаний стан не мусить
 * лишатися в історії, інакше «назад» повертає в нього.
 *
 * ## Що НЕ чіпається
 *
 * Чуже. Кожен крок обмежений цим застосунком — префіксом сховища й `scope`
 * реєстрації (`ownScope.ts`). Дошки в базі теж лишаються: скидання прибирає
 * локальний стан, а не чужу роботу. Пароль збереженої дошки при цьому
 * зникає — про це попереджає текст підтвердження.
 */

/** Скільки чого прибрано. Потрібне викликачу для журналу й для тексту. */
export interface ResetReport {
	keys: number;
	caches: number;
	workers: number;
}

/**
 * Прибрати локальний стан цього застосунку й перезавантажитися.
 *
 * Помилку на будь-якому кроці НЕ ковтаємо мовчки: половина прибраного це теж
 * результат, і перезавантажитися однаково треба — інакше людина лишається на
 * тому самому зламаному екрані, тепер ще й із порожніми налаштуваннями.
 */
export async function hardReset(): Promise<ResetReport> {
	const report: ResetReport = { keys: 0, caches: 0, workers: 0 };

	report.keys = clearOwn();

	try {
		report.workers = await unregisterOwnServiceWorkers();
	} catch {
		/* воркера могло не бути взагалі — це не привід спинятися */
	}

	try {
		report.caches = await deleteOwnCaches();
	} catch {
		/* те саме */
	}

	const url = new URL(window.location.href);
	url.searchParams.set('reset', String(Date.now()));
	// На корінь застосунку, а не на поточну адресу: скидання роблять саме тоді,
	// коли поточна сторінка й не відкривається.
	url.pathname = `${base || ''}/`;
	window.location.replace(url.toString());

	return report;
}
