import { runningInTauri } from '$lib/audio/tauriSource';

/**
 * ОНОВЛЕННЯ ВСТАНОВЛЕНОЇ ОБОЛОНКИ — і чому воно тут окреме від оновлення
 * сторінки.
 *
 * ## Дві різні речі, які легко сплутати
 *
 * Видима частина AudioRemote приходить із мережі й оновлюється сама: новий
 * service worker стає в `waiting`, людина бачить пропозицію
 * (`ReloadPrompt.svelte`). Це оновлення КОДУ СТОРІНКИ, і exe до нього не
 * причетний.
 *
 * Оболонка — інше. У ній живе те, чого браузер не вміє: читання теки за
 * шляхом, і, головне, МЕЖА `remote.urls`, яка вирішує, чий код дістане доступ
 * до диска. Правка цієї межі доїжджає до залу лише з новим exe.
 *
 * Плутати їх не можна, тому це окремий модуль і окрема пропозиція в інтерфейсі:
 * «оновити сторінку» й «поставити нову версію застосунку» роблять різне, а
 * людина за плеєром мусить розуміти, що саме їй пропонують.
 *
 * ## Три стани, а не два
 *
 * «Оновлення немає» і «перевірити не вдалося» — РІЗНЕ, і другий стан
 * нормальний: налаштування оновлювача (адреса й відкритий ключ) лежать у
 * `tauri.conf.release.json`, який накладається лише в релізній збірці. У
 * збірці з дерева розробника перевірка не вдасться завжди, і читати це як «у
 * вас найновіша версія» не можна.
 *
 * ## Чого тут НЕМАЄ навмисно
 *
 * Автоматичного встановлення. Оновлення оболонки перезапускає застосунок, а
 * вкладка приймача — єдине, що грає звук у залі. Те саме правило, що й для
 * service worker (`updateCheck.ts`): рішення ухвалює людина, а не програма.
 * Тому модуль зветься `checkDesktopUpdate`, а `install` повертається окремою
 * функцією, яку ще треба викликати.
 */

export type DesktopUpdate =
	| { kind: 'none' }
	| { kind: 'unavailable'; reason: string }
	| { kind: 'ready'; version: string; install: () => Promise<void> };

/**
 * Чи є нова версія оболонки.
 *
 * У браузері одразу `unavailable`: там оновлення робить service worker, і це
 * зовсім інший шлях.
 */
export async function checkDesktopUpdate(): Promise<DesktopUpdate> {
	if (!runningInTauri()) {
		return { kind: 'unavailable', reason: 'не застосунок' };
	}

	try {
		/*
		 * Динамічний імпорт обовʼязковий: той самий бандл віддається браузерам,
		 * а `@tauri-apps/plugin-updater` при завантаженні чіпає міст, якого там
		 * немає. Так само зроблено в `tauriSource.ts`.
		 */
		const { check } = await import('@tauri-apps/plugin-updater');
		const update = await check();

		if (!update) return { kind: 'none' };

		return {
			kind: 'ready',
			version: update.version,
			install: async () => {
				await update.downloadAndInstall();
				/*
				 * У Windows `installMode: "passive"` показує смужку прогресу
				 * інсталятора й закриває застосунок сам, тож цей рядок
				 * виконується не завжди — і саме тому він останній.
				 */
				const { relaunch } = await import('@tauri-apps/plugin-process');
				await relaunch();
			}
		};
	} catch (error) {
		/*
		 * Сюди потрапляє і «немає мережі», і «канал не налаштований у цій
		 * збірці». Розрізнити їх тут нема з чого — плагін віддає рядок, — та й
		 * не треба: наслідок однаковий, і він не «все гаразд».
		 */
		return { kind: 'unavailable', reason: error instanceof Error ? error.message : String(error) };
	}
}
