import { readItem, writeItem } from './storage';

/**
 * ЩО ПОКАЗУВАТИ НА ТАБЛІ — вибір, який переживає перезавантаження.
 *
 * На екрані табла стоять дві великі речі — панель і журнал, — і людині за
 * пультом потрібна то одна, то обидві. Доти цей вибір не зберігався НІДЕ й
 * скидався на кожному перезавантаженні, при тому що сусідній вибір у тій самій
 * картці («привертання уваги») зберігався з першого дня. Це вибір про ЦЕЙ
 * екран: монітор за пультом не міняється між перезавантаженнями, а сторінку
 * перезавантажують щовечора.
 *
 * ## Чому лише табло
 *
 * В аудіодошки те саме питання вирішене інакше й дешевше: журнал згортається
 * кнопкою у власному заголовку. Там ховати більше нічого — дека й список
 * потрібні обидва, — і тривибірник відповідав би трьома варіантами, з яких два
 * означають «сховати щось одне». На таблі ж панель і журнал справді
 * рівноправні.
 */

export const VIEWS = ['both', 'main', 'log'] as const;
export type View = (typeof VIEWS)[number];

const KEY = 'view.info';
const isView = (value: unknown): value is View => VIEWS.includes(value as View);

class ScreenView {
	view = $state<View>('both');

	/**
	 * Підняти збережене. Кличе оболонка після монтування.
	 *
	 * Не в оголошенні: під передрендером `localStorage` існує (node 22+ кладе
	 * його в глобальну область) і НЕ порожній, тож читання запекло б у HTML
	 * вибір машини збірки.
	 */
	init(): void {
		const saved = readItem(KEY);
		if (isView(saved)) this.view = saved;
	}

	set(view: View): void {
		this.view = view;
		writeItem(KEY, view);
	}
}

export const screenView = new ScreenView();
