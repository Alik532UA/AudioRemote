import { onDestroy } from 'svelte';

/**
 * «ЗРОБЛЕНО» НА ДВІ СЕКУНДИ — ОДНЕ РІШЕННЯ В ОДНОМУ МІСЦІ.
 *
 * Кнопка, яка щось зробила мовчки, виглядає точнісінько як кнопка, яка нічого не
 * зробила. Тому після копіювання й після збереження на місці кнопки на дві
 * секунди зʼявляється «скопійовано» / «збережено» — і зникає само, бо це
 * квитанція, а не стан.
 *
 * ## Чому окремий модуль
 *
 * Той самий рядок (`прапорець = true` плюс `setTimeout` на 2000) стояв у
 * ВОСЬМИ місцях шести компонентів. Одне рішення у восьми копіях — це не
 * повторення заради зручності, а вісім рішень, які розійдуться на першій же
 * зміні; заразом усі вісім мали ту саму пару вад:
 *
 *  1. **Такт не знімався ніколи.** Два натискання поспіль давали два такти, і
 *     перший гасив напис за мить після другого натискання: «зроблено» блимало
 *     й зникало саме тоді, коли людина дивилася на нього.
 *  2. **Такт переживав сторінку.** Вікно, закрите за ці дві секунди, лишало по
 *     собі виклик, який пише в стан мертвого компонента.
 *
 * ## Чому фабрика, а не клас
 *
 * `onDestroy` реєструється ТУТ, у тілі фабрики, а не в місці виклику. Ціна
 * цього — межа, і вона названа: викликати `confirmed()` можна лише при
 * створенні компонента (у тілі `<script>`), бо саме там існує його життєвий
 * цикл. Поза компонентом такт нема кому зняти, тому такого вжитку немає й бути
 * не мусить.
 */

/**
 * Скільки висить квитанція.
 *
 * Дві секунди: досить, щоб побачити краєм ока, і замало, щоб напис устиг
 * набриднути на кнопці, яку тиснуть двічі поспіль.
 */
export const CONFIRMED_MS = 2000;

export interface Confirmed {
	/** Чи показувати «зроблено» просто зараз. */
	readonly on: boolean;
	/** Показати квитанцію (і почати відлік наново, якщо вона вже висить). */
	show(): void;
}

export function confirmed(ms: number = CONFIRMED_MS): Confirmed {
	let on = $state(false);
	let timer: ReturnType<typeof setTimeout> | null = null;

	const stop = (): void => {
		if (timer === null) return;
		clearTimeout(timer);
		timer = null;
	};

	onDestroy(stop);

	return {
		get on() {
			return on;
		},
		show() {
			// Наново, а не поверх: друге натискання заслуговує на повні дві
			// секунди, а не на залишок від першого.
			stop();
			on = true;
			timer = setTimeout(() => {
				timer = null;
				on = false;
			}, ms);
		}
	};
}
