import type { Command, CommandType } from '$lib/net/boardTypes';
import { countRemotes, type PresenceMap } from '$lib/net/presence';
import { PresenceEvents } from './presenceLog';

/**
 * ЩО ЩОЙНО СТАЛОСЯ НА АУДІОДОШЦІ — і чому цього досі не було.
 *
 * В інфодошки журнал є з першого дня, і саме він відповідає на питання, яке
 * ставлять після вистави: «а чому воно тоді заграло?». В аудіодошки того
 * самого питання не менше, а відповіді не було ніде. Звук запускають три
 * джерела — руки за пультом, чужий пульт по мережі й тригер за API, — і
 * розрізнити їх постфактум було неможливо в принципі.
 *
 * ## Тільки в пам'яті вкладки
 *
 * Не в базі й не в сховищі. У базі це був би четвертий вузол із власними
 * правилами й власним письменником заради даних, які читають рівно поки
 * дивляться на екран. У сховищі — рядки, що переживають вечір і вводять в
 * оману наступного дня. Журнал відповідає на «щойно», а «щойно» не зберігають.
 *
 * ## Назва треку НЕ запам'ятовується
 *
 * Лишається `trackId`, а підпис бере той, хто малює, — у нього є список. Копія
 * назви застрягла б у рядку назавжди: трек перейменували, і журнал показував
 * би старе ім'я поруч із новим у списку, тобто брехав би про те саме.
 */

/** Звідки прийшла дія. Різниця між ними — це і є головне тут. */
export type DeckSource = 'self' | 'remote' | 'api';

export interface DeckNote {
	id: string;
	at: number;
	/**
	 * Що саме сталося.
	 *
	 * `trigger` — спрацював API; `came`/`went` — пульт прийшов або пішов; решта
	 * — звичайні команди.
	 */
	kind: CommandType | 'trigger' | 'came' | 'went';
	/** Трек, якого це стосується. Порожньо — дія не про конкретний трек. */
	trackId: string;
	/** Число команди: гучність або позиція перемотки. */
	value: number | null;
	source: DeckSource;
	/** Як підписався той, хто натиснув. Порожньо — не називався. */
	who: string;
}

/** Скільки рядків тримати. Далі найстаріші випадають — як і в інфодошці. */
const KEPT = 40;

class DeckLog {
	notes = $state<DeckNote[]>([]);

	private beat = 0;

	private readonly comings = new PresenceEvents('remote', ({ kind, who }) =>
		this.add({ kind, trackId: '', value: null, source: 'remote', who })
	);

	/**
	 * Команда з мережі. Пишеться ПІСЛЯ виконання — журнал каже, що сталося, а
	 * не що просили: відхилену команду (зниклий файл, прихований трек) до
	 * списку подій не заносимо.
	 */
	fromRemote(command: Command): void {
		this.add({
			kind: command.type,
			trackId: command.type === 'play' ? String(command.value ?? '') : '',
			value: typeof command.value === 'number' ? command.value : null,
			source: 'remote',
			who: command.name ?? ''
		});
	}

	/**
	 * Трек запустили НА САМОМУ приймачі: рукою, клавішею, чергою або тригером.
	 *
	 * Один вхід на всі місцеві шляхи навмисно. Їх шість (список, «далі»,
	 * «назад», гаряча клавіша, автоперехід, API), і рядок у кожному з них
	 * означав би, що сьомий шлях забудуть — мовчки, як і завжди.
	 */
	started(trackId: string, source: DeckSource): void {
		this.add({
			kind: source === 'api' ? 'trigger' : 'play',
			trackId,
			value: null,
			source,
			who: ''
		});
	}

	/**
	 * ЗНІМОК ПРИСУТНОСТІ — і журнал сам вирішує, що з нього стало рядком.
	 *
	 * Картка дошки каже, скільки пультів ЗАРАЗ; на питання «а коли він відпав»
	 * вона не відповідає ніяк — число просто стає іншим, і помітити це можна
	 * лише дивлячись на нього в ту саму секунду.
	 *
	 * Знімок приходить сирим, а не готовою подією, саме тому, що перетворення
	 * знімка на рядок — робота журналу: витримку на блимання мережі тримає
	 * `presenceLog.ts`, і приймачу не треба знати ні про неї, ні про те, що
	 * подій буває нуль.
	 *
	 * Повертає, скільки пультів на звʼязку: той самий знімок однаково вже
	 * розібрано, і другий прохід по ньому в місці виклику був би другим
	 * джерелом того самого числа.
	 */
	saw(present: PresenceMap): number {
		this.comings.see(present);
		return countRemotes(present);
	}

	/** Зняти витримки. Без цього вони вистрелять у журнал закритої дошки. */
	forget(): void {
		this.comings.stop();
		this.clear();
	}

	clear(): void {
		this.notes = [];
	}

	private add(note: Omit<DeckNote, 'id' | 'at'>): void {
		// Номер у ключі, а не сам час: дві дії в одну мілісекунду дали б
		// однаковий ключ, і `{#each}` намалював би одну замість двох.
		this.beat += 1;
		this.notes = [{ ...note, id: `${this.beat}`, at: Date.now() }, ...this.notes].slice(0, KEPT);
	}
}

export const deckLog = new DeckLog();
