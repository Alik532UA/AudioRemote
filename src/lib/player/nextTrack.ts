import type { PlayPolicy } from '$lib/audio/boardConfig';

/**
 * ЩО ГРАТИ ПІСЛЯ ТРЕКУ, ЯКИЙ ДОГРАВ САМ.
 *
 * Окремою чистою функцією, бо тут сходяться три правила, і кожне з них легко
 * перевірити лише числами: рід повторення, наявність наступного в списку й те,
 * що список міг змінитися, поки трек звучав.
 *
 * ## Порядок правил не випадковий
 *
 * «Повторювати трек» діє ПЕРШИМ і не питає про автоперехід: воно нікуди не
 * переходить, а отже суперечності тут немає. Наступне правило — сам
 * автоперехід; «повторювати список» без нього не означає нічого, бо нічого не
 * рухається, і на екрані про це сказано прямо.
 *
 * ## Список береться ПОТОЧНИЙ, а не той, що був на початку треку
 *
 * Поки трек звучав, папку могли перечитати, а трек — прибрати чи сховати.
 * Тому «наступний» шукається в тому списку, який є ЗАРАЗ, а зниклий трек не
 * дає наступного взагалі: продовжувати з місця, якого немає, нема звідки.
 */

/**
 * Мінімум між двома САМОСТІЙНИМИ продовженнями.
 *
 * Файл нульової довжини кидає «догравати» одразу, тож «повторювати трек» на
 * ньому крутилося б сотні разів на секунду й вішало вкладку. Чверть секунди —
 * це менше за найкоротший звук, який має сенс у залі, і більше за будь-яке
 * коло.
 */
export const AUTO_MIN_MS = 250;

export function nextAfter(
	list: readonly { id: string }[],
	finished: string,
	policy: PlayPolicy
): string | null {
	const at = list.findIndex((entry) => entry.id === finished);
	if (at < 0) return null;

	if (policy.repeat === 'one') return finished;
	if (!policy.autoNext) return null;

	const next = list[at + 1];
	if (next) return next.id;

	return policy.repeat === 'all' ? (list[0]?.id ?? null) : null;
}
