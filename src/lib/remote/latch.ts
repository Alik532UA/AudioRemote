/**
 * СВОЄ ЗНАЧЕННЯ ТРИМАЄТЬСЯ, ДОКИ ПРИЙМАЧ ЙОГО НЕ ПІДТВЕРДИТЬ.
 *
 * ## Що ламалося
 *
 * Повзунки пульта — гучність і перемотка — стрибали туди-сюди після кожного
 * пересування. Не через мережу й не через підписку: через ЧАС.
 *
 * Пульт нічого не змінює сам, він шле команду. Поки та йде до приймача, поки
 * приймач її виконує й оголошує новий стан, минає кількасот мілісекунд. А
 * захист «не чіпати, поки палець на повзунку» знімався на відпусканні пальця —
 * тобто ДО того, як команда взагалі пішла (гучність надсилається із затримкою в
 * 150 мс, щоб не сипати командами на кожен піксель). У цю щілину прилітало
 * останнє оголошення зі СТАРИМ значенням, повзунок відскакував назад, а за
 * мить приїжджало нове — і він стрибав удруге.
 *
 * На приймачі цього немає й бути не може: він міняє власний стан, і чекати
 * нема на кого.
 *
 * ## Що робить засувка
 *
 * Тримає те, що наказала людина, доки не прийде оголошення З ЦИМ САМИМ
 * значенням. Прийшло — засувка відпускається, далі показується стан приймача,
 * як і раніше.
 *
 * ## Чому є межа часу
 *
 * Підтвердження може не прийти ніколи: приймач закрили, мережа впала, гучність
 * уперлася в межу й він оголосив не те, що просили. Засувка без межі означала б
 * повзунок, який назавжди показує вигадку. Тому за `holdMs` вона відпускається
 * сама — і людина бачить те, що є насправді.
 */

export interface Latch<T> {
	/** Ми щойно наказали це значення. */
	set(value: T, now: number): void;
	/** Що показувати: своє, доки приймач не підтвердив, інакше його. */
	show(incoming: T, now: number): T;
	/** Чи тримаємо зараз своє. Для розмітки, яка показує щось інакше. */
	readonly held: boolean;
}

export function createLatch<T>(
	/** Чи це вже воно. Для гучності — рівність, для позиції — з допуском. */
	same: (mine: T, incoming: T) => boolean,
	holdMs: number
): Latch<T> {
	let mine: { value: T; until: number } | null = null;

	return {
		set(value, now) {
			mine = { value, until: now + holdMs };
		},

		show(incoming, now) {
			if (!mine) return incoming;

			// Підтвердили — засувка більше не потрібна.
			if (same(mine.value, incoming)) {
				mine = null;
				return incoming;
			}

			// Не дочекалися. Показуємо правду, якою б вона не була.
			if (now >= mine.until) {
				mine = null;
				return incoming;
			}

			return mine.value;
		},

		get held() {
			return mine !== null;
		}
	};
}

/** Скільки тримати гучність. Команда йде із затримкою 150 мс плюс дорога туди й назад. */
export const VOLUME_HOLD_MS = 2000;

/**
 * Скільки тримати позицію. Довше за гучність: приймачеві треба ще перемотати
 * файл, а на довгому треку це не миттєво.
 */
export const SEEK_HOLD_MS = 3000;

/**
 * Допуск для позиції — півтори секунди.
 *
 * Точної рівності тут не буде ніколи: приймач перемотує до найближчого кадру, а
 * якщо трек грає, то поки оголошення дійде, позиція вже трохи інша. Надто малий
 * допуск означав би, що підтвердження не настає, і засувка щоразу відпускалася б
 * за часом — тобто стрибок повертався б, лише пізніше.
 */
export const SEEK_TOLERANCE_MS = 1500;
