/**
 * ФОРМА ДАНИХ ІНФОДОШКИ — і чому вона живе окремо від аудіо.
 *
 * `boardTypes.ts` описує дошку, у якої є папка з музикою: `library`, `state`,
 * тривалість треку. Інфодошка не має з цього нічого — у неї немає ні файлів,
 * ні відтворення. Спільним лишається рівно те, що й мусить: адреса дошки,
 * присутність, журнал команд із квитанцією й `info`. Тримати обидві форми в
 * одному файлі означало б, що читач щоразу з'ясовує, яка половина зараз його.
 *
 * ## Навіщо взагалі другий вид дошки
 *
 * Помічник у залі не може докричатися до звукорежисера за пультом. Жести
 * двозначні, месенджер повільний, а в телефон звукорежисер не дивиться. Тут
 * він натискає підписану кнопку, і на екрані пульта з'являється рядок:
 * «Мікрофон — гучніше».
 *
 * ## Два вузли, і в кожного ОДИН письменник
 *
 * | Вузол | Хто пише | Що це |
 * |---|---|---|
 * | `panel` | господар (і адміністратор командою) | які комірки, що в них, як підписані |
 * | `panelState` | ГОСПОДАР | положення повзунків і чекбоксів ЗАРАЗ |
 * | `cmd/{id}` | будь-хто на дошці, лише створити | «натиснули оце» |
 * | `ack/{id}` | господар | «бачу» — тут це ЛЮДИНА, а не машина |
 *
 * СТАН ПИШЕ ГОСПОДАР, А НЕ ТОЙ, ХТО НАТИСНУВ, і це не формальність. Журнал
 * мусить казати «було 40% стало 60%», тобто обидві сторони зобов'язані бачити
 * одне й те саме «було». Якби стан писав кожен, хто торкнувся повзунка, вузол
 * мав би багатьох письменників — а на правилі «один письменник» тримається
 * вся схема доступу цього проєкту. Тому помічник надсилає НАМІР («гучніше»),
 * а господар обчислює нове значення й кладе його назад. Помічник бачить
 * результат тим самим шляхом, яким пульт бачить `state` плеєра.
 *
 * ## Квитанція означає «табло прийняло», а не «людина побачила»
 *
 * Спокуса зробити її другим — щоб помічник бачив «прочитано», а не «доїхало» —
 * велика, і від неї тут свідомо відмовлено. Квитанцію ставить той самий
 * `watchCommands`, що й в аудіодошці: він відповідає, щойно оброблювач
 * повернувся. Щоб відповідати НАТИСКАННЯМ звукорежисера, канал мусив би вміти
 * тримати команду відкритою хвилинами — іншого роду механізм, і до нього
 * `ACK_TIMEOUT_MS` у шість секунд не має стосунку.
 *
 * Тобто помічник бачить рівно те, що доведено: прохання доїхало до табло й
 * лягло в журнал. Це менше, ніж «прочитано», і саме так воно й називається на
 * екрані.
 */

import type { Ack, Command } from './boardTypes';

/**
 * РОЗМІР СІТКИ — три на п'ять, і він незмінний.
 *
 * Фіксована сітка коштує підписів: на телефоні шириною 390 px комірка виходить
 * приблизно 118 px, і довгий підпис туди не влазить. Натомість вона дає те,
 * чого не дає жодне перетікання, — СТАЛЕ МІСЦЕ. У темному залі рука йде до
 * кнопки, яку пам'ятає, а не до тієї, яку треба спершу прочитати.
 */
export const PANEL_COLS = 3;
export const PANEL_ROWS = 5;
export const PANEL_CELLS = PANEL_COLS * PANEL_ROWS;

/**
 * Скільки кнопок дозволено в одному віджеті.
 *
 * П'ять, бо стільки рядів у сітці: віджет стовпчиком може бути заввишки з
 * колонку, і це його природна межа. Доти було чотири — межа тісної клітинки,
 * у якій кнопки ділили одну висоту на всіх; клітинок тепер стільки, скільки
 * кнопок (див. `panel/layout.ts`).
 */
export const MAX_BUTTONS = PANEL_ROWS;

/** Межі тексту. Ті самі числа стоять у правилах бази — там вони й перевіряються. */
export const MAX_LABEL = 24;
export const MAX_CAPTION = 24;

/** Межі кроку повзунка. Ті самі числа стоять у правилах бази. */
export const MIN_STEP = 1;
export const MAX_STEP = 50;

/**
 * Положення повзунка, якого ще ніхто не чіпав.
 *
 * Середина, а не нуль: повзунок тут не має «вимкненого» кінця — він каже, чого
 * просять відносно того, що є зараз. Нуль читався б як «звук прибрано».
 */
export const DEFAULT_LEVEL = 50;

/**
 * Що саме стоїть у комірці.
 *
 * `buttons` — група підписаних кнопок («вверх гучніше», «центр ок», «вниз
 * тихіше»). `slider` — повзунок із кроком. `check` — перемикач так/ні.
 */
export type CellKind = 'buttons' | 'slider' | 'check';

export interface PanelButton {
	/** Що написано на кнопці. */
	label: string;
}

export interface PanelCell {
	/** Номер комірки, 0…14. Ключ у мапі, тож у значенні його немає. */
	kind: CellKind;
	/** Підпис усієї комірки: «фонограма», «мікрофон». Може бути порожній. */
	caption: string;
	/** Лише для `buttons`. Порядок у масиві — порядок на екрані. */
	buttons?: PanelButton[];
	/** Лише для `slider`: на скільки міняє одне натискання. */
	step?: number;
	/**
	 * Органи стоять стовпчиком. Відсутнє — так само стовпчиком.
	 *
	 * Поворот міняє не вигляд, а МІСЦЕ: три кнопки стовпчиком — третина висоти
	 * однієї колонки, три кнопки рядком — цілий ряд сітки на всю ширину.
	 * Скільки клітинок і де саме, рахує `panel/layout.ts`.
	 */
	vertical?: boolean;
}

/**
 * ПАНЕЛЬ — мапа за номером комірки, а не масив на п'ятнадцять.
 *
 * Порожні комірки в масиві довелося б чимось заповнювати, і кожен читач
 * вигадував би, чим саме. Мапа каже те саме коротше: комірки немає — вона
 * порожня.
 */
export interface Panel {
	/** Номер редакції. Адміністратор шле правку разом із тим, що бачив. */
	rev: number;
	/** Ключ — номер комірки рядком, `'0'`…`'14'`. */
	cells: Record<string, PanelCell>;
}

/**
 * Положення органів ЗАРАЗ. Пише лише господар — див. докблок файлу.
 *
 * Ключ той самий, що й у `panel.cells`. Комірки-кнопки стану не мають: кнопка
 * не тримає положення, вона лише просить.
 */
export interface PanelState {
	/** Повзунки: номер комірки → 0…100. */
	levels?: Record<string, number>;
	/** Чекбокси: номер комірки → увімкнено. */
	flags?: Record<string, boolean>;
	/** Серверний час останньої зміни. */
	atServer: number;
}

/**
 * ЩО МОЖНА ПОПРОСИТИ.
 *
 * `press` — натиснули кнопку в групі; `value` несе номер кнопки. `bump` —
 * посунули повзунок; `value` додатний або від'ємний крок. `toggle` —
 * перемкнули чекбокс. Номер комірки їде окремим полем: він потрібен усім трьом.
 */
export type PanelCommandType = 'press' | 'bump' | 'toggle';

/**
 * Команда інфодошки — той самий конверт, що й в аудіо, плюс номер комірки.
 *
 * Журнал, межа життя, серверний час і квитанція беруться з `commands.ts` без
 * жодної зміни: канал там задається шляхом, а тип команди — параметром.
 */
export interface PanelCommand extends Command<PanelCommandType> {
	/** Номер комірки, `'0'`…`'14'`. */
	cell: string;
}

/** Квитанція тут означає «людина побачила». Форма та сама, що в аудіо. */
export type PanelAck = Ack;
