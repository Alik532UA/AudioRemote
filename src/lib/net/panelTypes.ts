/**
 * ФОРМА ДАНИХ ІНФОДОШКИ — і чому вона живе окремо від аудіо.
 *
 * `boardTypes.ts` описує дошку, у якої є папка з музикою: `library`, `state`,
 * тривалість треку. Інфодошка не має з цього нічого — у неї немає ні файлів,
 * ні відтворення. Спільним лишається рівно те, що й мусить: адреса дошки,
 * присутність, журнал команд із квитанцією й `info`. Тримати обидві форми в
 * одному файлі означало б, що читач щоразу з'ясовує, яка половина зараз його.
 *
 * ## Навіщо взагалі другий вид дошки
 *
 * Помічник у залі не може докричатися до звукорежисера за пультом. Жести
 * двозначні, месенджер повільний, а в телефон звукорежисер не дивиться. Тут
 * він натискає підписану кнопку, і на екрані пульта з'являється рядок:
 * «Мікрофон — гучніше».
 *
 * ## Два вузли, і в кожного ОДИН письменник
 *
 * | Вузол | Хто пише | Що це |
 * |---|---|---|
 * | `panel` | господар (і адміністратор командою) | які комірки, що в них, як підписані |
 * | `panelState` | ГОСПОДАР | положення повзунків і чекбоксів ЗАРАЗ |
 * | `cmd/{id}` | будь-хто на дошці, лише створити | «натиснули оце» |
 * | `ack/{id}` | господар | «бачу» — тут це ЛЮДИНА, а не машина |
 *
 * СТАН ПИШЕ ГОСПОДАР, А НЕ ТОЙ, ХТО НАТИСНУВ, і це не формальність. Журнал
 * мусить казати «було 40% стало 60%», тобто обидві сторони зобов'язані бачити
 * одне й те саме «було». Якби стан писав кожен, хто торкнувся повзунка, вузол
 * мав би багатьох письменників — а на правилі «один письменник» тримається
 * вся схема доступу цього проєкту. Тому помічник надсилає НАМІР («гучніше»),
 * а господар обчислює нове значення й кладе його назад. Помічник бачить
 * результат тим самим шляхом, яким пульт бачить `state` плеєра.
 *
 * ## Квитанція означає «табло прийняло», а не «людина побачила»
 *
 * Спокуса зробити її другим — щоб помічник бачив «прочитано», а не «доїхало» —
 * велика, і від неї тут свідомо відмовлено. Квитанцію ставить той самий
 * `watchCommands`, що й в аудіодошці: він відповідає, щойно оброблювач
 * повернувся. Щоб відповідати НАТИСКАННЯМ звукорежисера, канал мусив би вміти
 * тримати команду відкритою хвилинами — іншого роду механізм, і до нього
 * `ACK_TIMEOUT_MS` у шість секунд не має стосунку.
 *
 * Тобто помічник бачить рівно те, що доведено: прохання доїхало до табло й
 * лягло в журнал. Це менше, ніж «прочитано», і саме так воно й називається на
 * екрані.
 */

import type { Ack, Command } from './boardTypes';

/**
 * РОЗМІР СІТКИ — три на п'ять типово, але не назавжди.
 *
 * Фіксована сітка коштує підписів: на телефоні шириною 390 px комірка виходить
 * приблизно 118 px, і довгий підпис туди не влазить. Натомість вона дає те,
 * чого не дає жодне перетікання, — СТАЛЕ МІСЦЕ. У темному залі рука йде до
 * кнопки, яку пам'ятає, а не до тієї, яку треба спершу прочитати.
 *
 * Стале місце потрібне СІТЦІ, а не саме цьому її розміру. Три на п'ять —
 * добрий початок для телефона в руці; планшет на стійці біля пульта тримає
 * більше, а дошка на дві кнопки не мусить малювати тринадцять порожніх місць.
 * Тому розмір тепер властивість панелі, а не застосунку, — і міняють його
 * рівно там, де панель складають.
 *
 * Межі є й вони не косметичні. Понад шість стовпців комірка на телефоні стає
 * вужчою за палець; понад вісім рядів сітка перестає вміщатися в екран без
 * прокрутки, а прокрутка вбиває наосліп (`components/panel/PanelGrid.svelte`).
 */
export const PANEL_COLS = 3;
export const PANEL_ROWS = 5;
export const PANEL_CELLS = PANEL_COLS * PANEL_ROWS;

export const MAX_PANEL_COLS = 6;
export const MAX_PANEL_ROWS = 8;
/** Найбільша можлива кількість комірок. Від неї залежать межі ключів у правилах. */
export const MAX_PANEL_CELLS = MAX_PANEL_COLS * MAX_PANEL_ROWS;

export interface Grid {
	rows: number;
	cols: number;
}

const gridWhole = (value: unknown, max: number): boolean =>
	Number.isInteger(value) && (value as number) >= 1 && (value as number) <= max;

/**
 * РОЗМІР ЦІЄЇ панелі — з неї самої або типовий.
 *
 * Обидва числа разом або жодного, як і в розмірі віджета: «шість стовпців, а
 * рядів як вийде» дало б дві відповіді на одне питання. Панелі, складені до
 * появи розміру, читаються як три на п'ять — тобто саме так, як виглядали.
 */
export function gridOf(panel: Pick<Panel, 'cols' | 'rows'>): Grid {
	if (gridWhole(panel.rows, MAX_PANEL_ROWS) && gridWhole(panel.cols, MAX_PANEL_COLS)) {
		return { rows: panel.rows as number, cols: panel.cols as number };
	}
	return { rows: PANEL_ROWS, cols: PANEL_COLS };
}

/**
 * Скільки кнопок дозволено в одному віджеті.
 *
 * П'ять, бо стільки рядів у сітці: віджет стовпчиком може бути заввишки з
 * колонку, і це його природна межа. Доти було чотири — межа тісної клітинки,
 * у якій кнопки ділили одну висоту на всіх; клітинок тепер стільки, скільки
 * кнопок (див. `panel/layout.ts`).
 */
export const MAX_BUTTONS = PANEL_ROWS;

/** Межі тексту. Ті самі числа стоять у правилах бази — там вони й перевіряються. */
export const MAX_LABEL = 24;
export const MAX_CAPTION = 24;
/** Підпис помічника в журналі. Довший не вміщається в рядок. */
export const MAX_WHO = 24;
/** Назва пульта. Коротка навмисно: вона стоїть у ряду перемикачів. */
export const MAX_SHEET = 16;
/**
 * Межа значка. Шістнадцять, бо одне емодзі — це не один символ: родина з
 * чотирьох людей і прапор із модифікатором легко дають десяток одиниць UTF-16.
 * Те саме число стоїть у треків (`MAX_ICON` у `boardConfig.ts`).
 */
export const MAX_PANEL_ICON = 16;

/** Межі кроку повзунка. Ті самі числа стоять у правилах бази. */
export const MIN_STEP = 1;
export const MAX_STEP = 50;

/**
 * Положення повзунка, якого ще ніхто не чіпав.
 *
 * Середина, а не нуль: повзунок тут не має «вимкненого» кінця — він каже, чого
 * просять відносно того, що є зараз. Нуль читався б як «звук прибрано».
 */
export const DEFAULT_LEVEL = 50;

/**
 * Що саме стоїть у комірці.
 *
 * `buttons` — група підписаних кнопок («вверх гучніше», «центр ок», «вниз
 * тихіше»). `slider` — повзунок із кроком. `check` — перемикач так/ні.
 */
export type CellKind = 'buttons' | 'slider' | 'check';

export interface PanelButton {
	/** Що написано на кнопці. */
	label: string;
	/**
	 * Заготовка кольору саме цієї кнопки. Відсутня — колір усього віджета.
	 *
	 * Окремо від кольору віджета, бо питання різні. Колір віджета каже, ДЕ він
	 * у сітці («мікрофон — зелений»); колір кнопки каже, ЩО вона робить
	 * («тихіше — червона»). У темряві друге читається швидше за підпис.
	 */
	color?: string;
}

export interface PanelCell {
	/** Номер комірки, 0…14. Ключ у мапі, тож у значенні його немає. */
	kind: CellKind;
	/** Підпис усієї комірки: «фонограма», «мікрофон». Може бути порожній. */
	caption: string;
	/**
	 * Заготовка кольору з `config/trackColors.ts`. Відсутня — без кольору.
	 *
	 * Та сама палітра, що й у треків, і з тієї ж причини: у темному залі шукають
	 * очима те, що впізнають, і колір робить це швидше за підпис. Слугом, а не
	 * кодом: палітру тоді можна підправити однією правкою на весь застосунок.
	 */
	color?: string;
	/** Значок у підписі — емодзі. Відсутній — без значка. */
	icon?: string;
	/** Лише для `buttons`. Порядок у масиві — порядок на екрані. */
	buttons?: PanelButton[];
	/** Лише для `slider`: на скільки міняє одне натискання. */
	step?: number;
	/**
	 * Органи стоять стовпчиком. Відсутнє — так само стовпчиком.
	 *
	 * Поворот міняє не вигляд, а МІСЦЕ: три кнопки стовпчиком — третина висоти
	 * однієї колонки, три кнопки рядком — цілий ряд сітки на всю ширину.
	 * Скільки клітинок і де саме, рахує `panel/layout.ts`.
	 */
	vertical?: boolean;
	/**
	 * СВІЙ РОЗМІР у клітинках. Обидва разом або жодного.
	 *
	 * Типово розмір виводиться з кількості органів: п'ять кнопок — п'ять
	 * клітинок. Це добре для типового випадку й погано для всіх інших: п'ять
	 * кнопок на пів колонки бувають потрібні рідше, ніж п'ять кнопок дрібніше,
	 * але в трьох клітинках. Тому розмір можна назвати прямо, і тоді органи
	 * розкладаються всередині названого прямокутника.
	 */
	rows?: number;
	cols?: number;
	/**
	 * ЧИЙ ЦЕ ПУЛЬТ. Порожньо — віджет спільний, його бачать усі.
	 *
	 * У залі помічників буває кілька, і роботи в них різні: один веде світло,
	 * другий завісу, третій підказує текст. Одна панель на всіх означала, що
	 * кожен шукає свої три кнопки серед чужих п'ятнадцяти — тобто саме те, чого
	 * фіксована сітка мала б не допускати.
	 *
	 * Назва довільна, бо перелік пультів — це перелік людей у конкретному залі,
	 * і вгадати його нізвідки. Помічник обирає свою назву на своєму екрані, і
	 * вибір лишається в його телефоні.
	 *
	 * ## Віджет БЕЗ назви бачать усі — і це відповідь на «об'єднати»
	 *
	 * «Стоп» і «готові» потрібні кожному, хто в залі, тож порожнє поле означає
	 * «спільний». Панель, у якій жоден віджет не названий, виглядає в усіх
	 * однаково — тобто рівно так, як вона виглядала досі.
	 */
	sheet?: string;
	/**
	 * ГУЧНЕ НАТИСКАННЯ: екран табла на мить перемикається на протилежну тему.
	 *
	 * Для того, чого не можна проґавити: «стоп», «тривога», «завіса». Підсвітка
	 * кнопки й рядок у журналі працюють лише тоді, коли на екран дивляться, а
	 * звукорежисер дивиться на сцену. Спалах усього екрана видно боковим зором.
	 */
	important?: boolean;
}

/**
 * ПАНЕЛЬ — мапа за номером комірки, а не масив на п'ятнадцять.
 *
 * Порожні комірки в масиві довелося б чимось заповнювати, і кожен читач
 * вигадував би, чим саме. Мапа каже те саме коротше: комірки немає — вона
 * порожня.
 */
export interface Panel {
	/** Номер редакції. Адміністратор шле правку разом із тим, що бачив. */
	rev: number;
	/**
	 * РОЗМІР СІТКИ. Обидва разом або жодного — тоді три на п'ять.
	 *
	 * Комірки, що опинилися за межею зменшеної сітки, НЕ стираються: їх просто
	 * не видно, доки сітку не повернуть. Стирати їх означало б, що помилковий
	 * дотик до лічильника коштує вечора роботи, а мовчазне зникнення даних —
	 * найгірше, що вміє застосунок.
	 */
	cols?: number;
	rows?: number;
	/** Ключ — номер комірки рядком, від `'0'`. */
	cells: Record<string, PanelCell>;
}

/**
 * Положення органів ЗАРАЗ. Пише лише господар — див. докблок файлу.
 *
 * Ключ той самий, що й у `panel.cells`. Комірки-кнопки стану не мають: кнопка
 * не тримає положення, вона лише просить.
 */
export interface PanelState {
	/** Повзунки: номер комірки → 0…100. */
	levels?: Record<string, number>;
	/** Чекбокси: номер комірки → увімкнено. */
	flags?: Record<string, boolean>;
	/** Серверний час останньої зміни. */
	atServer: number;
}

/**
 * ЩО МОЖНА ПОПРОСИТИ.
 *
 * `press` — натиснули кнопку в групі; `value` несе номер кнопки. `bump` —
 * посунули повзунок; `value` додатний або від'ємний крок. `toggle` —
 * перемкнули чекбокс. Номер комірки їде окремим полем: він потрібен усім трьом.
 */
export type PanelCommandType = 'press' | 'bump' | 'toggle';

/**
 * Команда інфодошки — той самий конверт, що й в аудіо, плюс номер комірки.
 *
 * Журнал, межа життя, серверний час і квитанція беруться з `commands.ts` без
 * жодної зміни: канал там задається шляхом, а тип команди — параметром.
 */
export interface PanelCommand extends Command<PanelCommandType> {
	/** Номер комірки, `'0'`…`'14'`. */
	cell: string;
	/**
	 * ЯК ПІДПИСАВСЯ той, хто натиснув. Немає — анонімно, як і було.
	 *
	 * Їде разом із проханням, а не питається окремо в присутності: присутність
	 * каже, хто ЗАРАЗ на звʼязку, а журнал читають і через годину — коли того,
	 * хто просив, уже немає на лінії. Підпис мусить лишитися в рядку назавжди.
	 *
	 * Це ПІДПИС, а не посвідчення: він не перевіряється й нічого не відкриває.
	 * Двоє можуть назватися однаково, і база цьому не завадить — так само, як
	 * не завадила б двом однаковим іменам у житті.
	 */
	name?: string;
}

/** Квитанція тут означає «людина побачила». Форма та сама, що в аудіо. */
export type PanelAck = Ack;

/**
 * ВІДПОВІДЬ ЗВУКОРЕЖИСЕРА НА ПРОХАННЯ — і чому вона взагалі потрібна.
 *
 * Помічник у залі натиснув «гучніше» й далі не знає нічого. Квитанція
 * (`PanelAck`) каже лише, що вкладка табла відкрита, — не те, що людина
 * прохання ПОБАЧИЛА, і вже точно не те, що вона його виконала. Різниця між
 * «не помітив» і «зараз не можу» — це різниця між «піти й сказати вголос» і
 * «почекати», а в темному залі під час вистави це дороге рішення.
 *
 * Три відповіді, а не дві. «Ні» і «тимчасові складнощі» — не відтінки одного:
 * перше означає «не буде, шукай інший вихід», друге — «буде, але не зараз».
 *
 * ## Один вузол, а не журнал
 *
 * Відповідь відповідає на питання «що зі мною щойно погодилися зробити», і
 * відповідь на нього одна — остання. Журнал відповідей був би другим журналом
 * поруч із тим, що вже є, і жив би вічно; цей вузол перезаписується.
 */
export type VerdictKind = 'done' | 'no' | 'wait';

export interface PanelVerdict {
	kind: VerdictKind;
	/** Комірка, якої стосується відповідь. */
	cell: string;
	/** Підпис комірки, щоб помічник не шукав очима, про що йдеться. */
	caption: string;
	/** Серверний час. За ним видно, чи відповідь свіжа. */
	at: number;
}

/** Скільки відповідь вважається свіжою: старішу помічникові не показуємо. */
export const VERDICT_FRESH_MS = 20000;
