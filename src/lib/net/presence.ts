import { boardPath } from '$lib/board/boardPath';
import { connect } from './firebase';
import { MAX_SHEET, MAX_WHO } from './panelTypes';
import type { BoardRole } from '$lib/board/myBoards';

/**
 * ПРИСУТНІСТЬ — усе, що тримається на `onDisconnect`, тобто на обіцянці, яку
 * виконує СЕРВЕР, коли клієнт зник.
 *
 * ## Чому це окремий модуль
 *
 * Тут інша природа записів. Бібліотека й стан — те, що застосунок пише
 * навмисно і що мусить пережити обрив. Присутність навпаки: вона існує рівно
 * доти, доки живий сокет, і зникає без жодної участі коду. Змішані в одному
 * файлі, ці дві речі читаються як одна.
 *
 * ## Чому взагалі RTDB, а не щось інше
 *
 * Через `onDisconnect()`. Для цього застосунку питання «комп'ютер на зв'язку чи
 * вкладку закрили» — не дрібниця інтерфейсу, а головне, що людина з телефоном
 * хоче знати ПЕРЕД тим, як натиснути. Клієнт сам про свій обрив не напише: у
 * тому єдиному випадку, для якого присутність і існує — вкладку закрили, кришку
 * ноутбука опустили, зв'язок зник у коридорі, — писати вже нікому.
 *
 * ## Ключ — НЕ `uid`, а `uid` плюс вкладка. Заміряно.
 *
 * Спершу присутність лежала в `presence/{uid}`, і на двох пристроях це
 * працювало. Ламалося воно рівно тоді, коли плеєр і пульт опинялися в ОДНОМУ
 * браузері: анонімний вхід дає обом вкладкам той самий `uid`, тож друга
 * перетирала запис першої. На екрані це виглядало так: плеєр відкритий і
 * працює, а пульт поруч каже «комп'ютер офлайн».
 *
 * Тепер шлях — `presence/{uid}/{вкладка}`. Правило доступу від цього не
 * послабилося ні на крок: дозвіл і далі стоїть на `$uid === auth.uid` і
 * поширюється на все, що під ним, тобто писати за іншого так само не можна.
 *
 * Ідентифікатор вкладки живе в пам'яті сторінки й не зберігається ніде:
 * присутність і так має зникнути разом із вкладкою.
 *
 * ## Порядок не косметичний
 *
 * Спершу домовляємось, ЩО прибрати, і лише тоді зʼявляємось. У зворотному
 * порядку існує вікно, у якому запис уже є, а домовленості про його прибирання
 * ще немає, — і зникнення клієнта саме в цю мить лишає привида назавжди.
 *
 * ## ЗʼЯВЛЯТИСЯ ДОВОДИТЬСЯ ЩОРАЗУ, А НЕ ОДИН РАЗ
 *
 * Це найдорожче місце файлу, і помилка тут читається як поломка іншого
 * пристрою. `onDisconnect` виконує СЕРВЕР: обірвався сокет — запис зник. SDK
 * при відновленні звʼязку наново домовляється про `onDisconnect`, але вже
 * підтверджений `set` він не повторює: для нього той запис давно вдався.
 *
 * Отже одноразове «зʼявитися» тримається рівно до першого блимання мережі.
 * П'ять секунд без Wi-Fi на пристрої, що грає, — і присутність зникла
 * НАЗАВЖДИ, хоч вкладка відкрита й музика грає. Пульт при цьому каже «Плеєр
 * офлайн. Дошку на пристрої, що грає, закрито. Відкрийте її там» — тобто
 * відправляє людину через усю залу до вкладки, яка працює.
 *
 * Тому зʼявлення підписане на `.info/connected` і повторюється на кожному
 * відновленні. Першого виклику окремо немає: цей же слухач приносить `true`
 * одразу, щойно сокет підніметься.
 */

const presencePath = (key: string) => `${boardPath(key)}/presence`;

/** Ідентифікатор ЦІЄЇ вкладки. Один на завантаження сторінки. */
const TAB_ID = Math.random().toString(36).slice(2, 10);

export interface Presence {
	role: BoardRole;
	at: number;
	/** Як назвався той, хто тут. Порожньо — не називався. */
	name?: string;
	/** Який пульт він обрав. Порожньо — дивиться всю дошку. */
	sheet?: string;
}

/**
 * ЩО ПРИСУТНІЙ ПРО СЕБЕ КАЖЕ — і чому це їде саме присутністю.
 *
 * Табло малює по панелі на кожен пульт, і поруч із кожною мусить стояти, хто
 * за ним зараз. Дізнатися це нізвідки більше: імʼя лежить у налаштуваннях
 * телефона, обраний пульт — у його ж сховищі, і жодне з двох до дошки не
 * доїжджає. Команда їх не несе теж: вона буває раз на десять хвилин, а питання
 * «хто на звʼязку» має відповідь щосекунди.
 *
 * Обидва поля НЕОБОВʼЯЗКОВІ й порожніми не пишуться: анонімний помічник, який
 * дивиться всю дошку, лишає рівно той самий запис, що й раніше.
 */
export interface PresenceAbout {
	name?: string;
	sheet?: string;
}

/**
 * Останнє, що ця вкладка про себе сказала, — по дошці.
 *
 * Потрібне тому, що зʼявлення ПОВТОРЮЄТЬСЯ на кожному відновленні звʼязку (див.
 * вище), і повторне мусить нести те, що правда ЗАРАЗ, а не те, що було при
 * відкритті сторінки. Інакше помічник, який змінив пульт і пережив блимання
 * мережі, повертався б на екран табла під старим пультом.
 */
const said = new Map<string, PresenceAbout>();

/**
 * Значення в межах, які приймає правило бази. `null` — поля не буде.
 *
 * ВКОРОЧУЄ ТУТ, А НЕ В МІСЦІ ВИКЛИКУ, і це не зайва обережність. Правило
 * присутності приймає імʼя до 24 символів і пульт до 16, а `$other: false`
 * відкидає незнане значення разом з УСІМ записом. Тобто задовге імʼя — це не
 * «присутність без підпису», а присутності немає взагалі: помічник зникає з
 * табла, а на пульті пише «плеєр офлайн», хоч усе на місці.
 *
 * Дотепер на це покладалися на тих, хто кличе: налаштування справді
 * вкорочують імʼя, а назви пультів приходять із редактора панелі, який теж
 * вкорочує. Але обидва значення дорогою лежать у сховищі, і жодне з двох
 * обмежень не видно звідси. Межа мусить триматися там, де пишуть, — інакше
 * наступний виклик звідкись іще принесе довший рядок, і симптом буде не про
 * нього.
 *
 * Порожнє не пишеться: `undefined` база не приймає, а `''` — це брехня («він
 * назвався нічим»).
 */
const fit = (value: string | undefined, max: number): string | null => {
	const text = value?.trim().slice(0, max) ?? '';
	return text.length > 0 ? text : null;
};

const trim = (about: PresenceAbout): Record<string, string> => {
	const out: Record<string, string> = {};
	const name = fit(about.name, MAX_WHO);
	const sheet = fit(about.sheet, MAX_SHEET);
	if (name) out.name = name;
	if (sheet) out.sheet = sheet;
	return out;
};

/** `presence/{uid}/{вкладка}` — два рівні, тому й тип вкладений. */
export type PresenceMap = Record<string, Record<string, Presence>>;

/** Тримати присутність, поки жива вкладка. Повертає функцію «піти явно». */
export async function trackPresence(
	key: string,
	role: BoardRole,
	about: PresenceAbout = {}
): Promise<() => void> {
	const { db, uid } = await connect();
	const { onDisconnect, onValue, ref, remove, serverTimestamp, set } =
		await import('firebase/database');

	said.set(key, about);
	const mine = ref(db, `${presencePath(key)}/${uid}/${TAB_ID}`);

	const announce = async (): Promise<void> => {
		await onDisconnect(mine).remove();
		await set(mine, { role, at: serverTimestamp(), ...trim(said.get(key) ?? {}) });
	};

	/*
	 * `.info/connected` — власний шлях SDK: правила на нього не поширюються, і
	 * читати його можна завжди. Він же приносить перше `true`, тож окремого
	 * першого зʼявлення тут немає — воно було б другим записом тієї самої миті.
	 */
	const unwatch = onValue(ref(db, '.info/connected'), (snapshot) => {
		if (snapshot.val() === true) void announce();
	});

	return () => {
		unwatch();
		said.delete(key);
		void remove(mine);
	};
}

/**
 * ПЕРЕКАЗАТИ ПРО СЕБЕ ЩЕ РАЗ — коли імʼя чи пульт змінилися на ходу.
 *
 * Окремою функцією, а не другим викликом `trackPresence`: той наново
 * домовляється про `onDisconnect`, і між зняттям старої домовленості й новою
 * існує вікно, у якому зникнення вкладки лишає привида назавжди.
 *
 * Мовчки виходить, якщо про цю дошку ще не зʼявлялися: писати присутність, не
 * тримаючи її, означало б лишити запис, який нікому прибрати.
 */
export async function tellPresence(key: string, about: PresenceAbout): Promise<void> {
	if (!said.has(key)) return;
	said.set(key, about);

	const { db, uid } = await connect();
	const { ref, update } = await import('firebase/database');
	await update(ref(db, `${presencePath(key)}/${uid}/${TAB_ID}`), {
		name: fit(about.name, MAX_WHO),
		sheet: fit(about.sheet, MAX_SHEET)
	});
}

/** Хто зараз на дошці. Повертає відписку. */
export async function watchPresence(
	key: string,
	onPresence: (present: PresenceMap) => void
): Promise<() => void> {
	const { db } = await connect();
	const { onValue, ref } = await import('firebase/database');
	return onValue(ref(db, presencePath(key)), (snapshot) =>
		onPresence((snapshot.val() as PresenceMap | null) ?? {})
	);
}

/** Усі записи присутності одним списком — рівні `uid` тут уже не важать. */
const entries = (present: PresenceMap): Presence[] =>
	Object.values(present).flatMap((tabs) => Object.values(tabs ?? {}));

/** Чи є серед присутніх плеєр — тобто чи є кому грати. */
export function hasPlayer(present: PresenceMap): boolean {
	return entries(present).some((entry) => entry.role === 'player');
}

/** Скільки пультів на зв'язку. Плеєр показує це, щоб було видно, хто керує. */
export function countRemotes(present: PresenceMap): number {
	return entries(present).filter((entry) => entry.role === 'remote').length;
}

/**
 * Підписи тих, хто назвався, — без повторів і без порожніх.
 *
 * Дві вкладки однієї людини дали б дві однакові мітки, а вона одна; анонімний
 * не дістає мітки зовсім — «без імені» не відповідає ні на що, а місце займає.
 * Скільки їх УСЬОГО, каже число поруч.
 */
export function namesOf(present: PresenceMap, role: BoardRole): string[] {
	const seen = entries(present)
		.filter((entry) => entry.role === role)
		.map((entry) => entry.name?.trim() ?? '')
		.filter(Boolean);
	return [...new Set(seen)];
}

/**
 * ЧИ ЖИВИЙ СОКЕТ ДО БАЗИ — і чому без цього застосунок бреше.
 *
 * SDK Realtime Database терпить обрив: запис лягає в локальну чергу, читання
 * повертає те, що щойно записали. Для застосунку, який працює з мережею
 * уривками, це рятівна властивість. Тут вона обертається проти нас: коли бази
 * немає зовсім — не задеплоєна, не та адреса, впав інтернет — сторінка
 * приймача виглядає БЕЗДОГАННО. Дошка «створилася», треки «оголосилися»,
 * жодної помилки в консолі. І тільки телефон з іншого кінця зали не бачить
 * нічого, і причину шукають у телефоні.
 *
 * `.info/connected` — власний шлях SDK, не наші дані: правила на нього не
 * поширюються, читати його можна завжди.
 */
export async function watchConnection(onChange: (online: boolean) => void): Promise<() => void> {
	const { db } = await connect();
	const { onValue, ref } = await import('firebase/database');
	return onValue(ref(db, '.info/connected'), (snapshot) => onChange(snapshot.val() === true));
}
