import { t } from '$lib/i18n/i18n.svelte';
import type { Panel, PanelButton } from '$lib/net/panelTypes';

/**
 * ТИПОВА ПАНЕЛЬ — ЩОБ ПЕРШИЙ ЕКРАН НЕ БУВ ПОРОЖНІМ АРКУШЕМ.
 *
 * Порожня сітка 3×5 не пояснює нічого: з неї не видно ні того, як виглядає
 * підпис, ні того, навіщо це все. Господар, який бачить складену панель,
 * править її; господар, який бачить порожнечу, закриває вкладку.
 *
 * ## Ставиться НАТИСКАННЯМ, а не сама
 *
 * Мовчазне заповнення дошки, якої людина ще не бачила, — це чужі дані на її
 * дошці: вона їх не просила й мусила б здогадатися, звідки вони взялися.
 * Кнопка каже, що станеться, до того, як воно стається.
 *
 * ## Підписи — ПЕРЕКЛАДЕНІ ОДИН РАЗ, і далі вони її
 *
 * Мова береться та, яка стоїть у мить натискання, і в базу лягає готовий
 * рядок. Ключа там бути не може: підписи пише людина, і наступним рухом вона
 * перейменує «мікрофон» на «мікрофон Олі». Панель, половина якої
 * перекладається, а половина ні, читалася б як зламана.
 *
 * ## ЧОМУ САМІ КНОПКИ, А НЕ ПО ВІДЖЕТУ КОЖНОГО РОДУ
 *
 * Доти тут стояв показ можливостей: два віджети по три кнопки, повзунок і
 * перемикач — «дивіться, комірки бувають трьох родів». Показ роду коштує
 * місця, а відповідає на питання, якого ніхто не ставить: що ще вміє
 * складальник, видно в самому складальнику, за одне натискання по порожній
 * комірці.
 *
 * Питання, яке ставлять, інше: «що я скажу звукорежисерові з залу». І
 * відповідь на нього — ШКАЛА, а не три кнопки: «трохи гучніше» й «гучніше» —
 * це різні прохання, і людина в залі розрізняє їх упевнено. Тому обидва
 * джерела дістали по п'ять сходинок від «гучніше» до «тихіше» й по власному
 * кольору: у темному залі колір знаходять швидше за підпис.
 *
 * Третя комірка — «увага» з позначкою важливої дії. Це єдине прохання, яке не
 * про звук, і єдине, що мусить дійти навіть до того, хто дивиться не на екран
 * (див. `important` у `panelTypes.ts`).
 */

/** П'ять сходинок гучності — від «гучніше» до «тихіше», як їх читають згори вниз. */
const scale = (): PanelButton[] => [
	{ label: t('panel.louder') },
	{ label: t('panel.louderBit') },
	{ label: t('panel.fine') },
	{ label: t('panel.quieterBit') },
	{ label: t('panel.quieter') }
];

export function starterPanel(): Panel {
	return {
		rev: Date.now(),
		/*
		 * ПО СТОВПЦЮ НА ДЖЕРЕЛО, і між ними — прохід. Віджет на п'ять кнопок
		 * стоїть стовпчиком і займає чотири ряди; два таких у крайніх колонках
		 * лишають середню вільною, і в ній стоїть «увага». Вона мала, її не
		 * плутають із гучністю й до неї не дотягуються випадково, тиснучи
		 * сусідню шкалу.
		 *
		 * Нижній ряд лишається порожнім навмисно: панель починають доповнювати,
		 * а не розбирати.
		 */
		cells: {
			'0': {
				kind: 'buttons',
				caption: t('panel.track'),
				color: 'coral',
				rows: 4,
				cols: 1,
				vertical: true,
				buttons: scale()
			},
			'2': {
				kind: 'buttons',
				caption: t('panel.mic'),
				color: 'violet',
				rows: 4,
				cols: 1,
				vertical: true,
				buttons: scale()
			},
			'4': {
				kind: 'buttons',
				caption: '',
				color: 'ruby',
				important: true,
				vertical: true,
				buttons: [{ label: t('panel.alarm') }]
			}
		}
	};
}
