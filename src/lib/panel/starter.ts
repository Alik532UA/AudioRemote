import { t } from '$lib/i18n/i18n.svelte';
import type { Panel } from '$lib/net/panelTypes';

/**
 * ТИПОВА ПАНЕЛЬ — ЩОБ ПЕРШИЙ ЕКРАН НЕ БУВ ПОРОЖНІМ АРКУШЕМ.
 *
 * Порожня сітка 3×5 не пояснює нічого: з неї не видно ні того, що комірки
 * бувають трьох родів, ні того, як виглядає підпис, ні того, навіщо це все.
 * Господар, який бачить складену панель, править її; господар, який бачить
 * порожнечу, закриває вкладку.
 *
 * ## Ставиться НАТИСКАННЯМ, а не сама
 *
 * Мовчазне заповнення дошки, якої людина ще не бачила, — це чужі дані на її
 * дошці: вона їх не просила й мусила б здогадатися, звідки вони взялися.
 * Кнопка каже, що станеться, до того, як воно стається.
 *
 * ## Підписи — ПЕРЕКЛАДЕНІ ОДИН РАЗ, і далі вони її
 *
 * Мова береться та, яка стоїть у мить натискання, і в базу лягає готовий
 * рядок. Ключа там бути не може: підписи пише людина, і наступним рухом вона
 * перейменує «мікрофон» на «мікрофон Олі». Панель, половина якої
 * перекладається, а половина ні, читалася б як зламана.
 */
export function starterPanel(): Panel {
	const three = () => [
		{ label: t('panel.louder') },
		{ label: t('panel.fine') },
		{ label: t('panel.quieter') }
	];

	return {
		rev: Date.now(),
		cells: {
			/*
			 * ПЕРШИЙ СТОВПЕЦЬ, А НЕ ПЕРШИЙ РЯДОК. Комірки 0 і 3 стоять одна під
			 * одною, і саме так їх і просять: два джерела звуку поруч, у кожного
			 * свої «гучніше — ок — тихіше». Рядком вони б розійшлися по екрану.
			 */
			'0': { kind: 'buttons', caption: t('panel.track'), buttons: three() },
			'3': { kind: 'buttons', caption: t('panel.mic'), buttons: three() },
			'6': { kind: 'slider', caption: t('panel.overall'), step: 10 },
			'9': { kind: 'check', caption: t('panel.ready') }
		}
	};
}
