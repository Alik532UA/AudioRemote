import type { PanelCommandType, PanelState } from '$lib/net/panelTypes';

/**
 * НАТИСКАННЯ У ВИГЛЯДІ, ЯКИЙ ЇДЕ В БАЗУ — щоб його побачили ВСІ.
 *
 * Поле `press` у стані органів існує заради одного: натискання за звуковим
 * пультом мусить бути видно в залі так само, як прохання із зали видно за
 * пультом. Складається воно тут, а не в сторінці, бо складається двічі — для
 * власної руки й для прохання, що приїхало, — і дві копії розійшлися б на
 * першій же правці.
 *
 * ЩО СЮДИ НЕ ПОТРАПЛЯЄ:
 *
 *  * рядкове значення. У базі поле числове (номер кнопки або крок повзунка), а
 *    рядок буває лише в розкладці, яку кожен екран рахує собі сам;
 *  * порожнє поле. RTDB не зберігає `undefined`, а порожній рядок у підписі
 *    означав би «назвався нічим» — тобто відповідь там, де відповіді немає.
 */
export interface Touched {
	cell: string;
	type: PanelCommandType;
	value?: string | number;
}

export const pressOf = (
	at: Touched,
	/** `uid` того, хто натиснув. Кожен екран упізнає свою руку порівнянням. */
	by: string,
	/** Як підписався. Порожньо — не називався. */
	who: string,
	/** Натиснули за звуковим пультом, а не в залі. */
	desk: boolean
): PanelState['press'] => ({
	cell: at.cell,
	type: at.type,
	...(typeof at.value === 'number' ? { value: at.value } : {}),
	...(by ? { by } : {}),
	...(who ? { name: who } : {}),
	...(desk ? { desk: true } : {})
});
