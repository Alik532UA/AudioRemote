// @vitest-environment node
import { describe, expect, it } from 'vitest';
import { largestFit } from './fit';

/**
 * ПОШУК РОЗМІРУ ПІДПИСУ — його межі й монотонність.
 *
 * Помилка тут тиха в обидва боки. Промах угору — і підпис знову зрізає край
 * кнопки, як зрізав до цього. Промах униз — і текст стає дрібнішим, ніж треба,
 * тобто повертається рівно та скарга, з якої все почалося. Тому перевіряються
 * саме краї: верхня межа, нижня межа, і що знайдене — справді НАЙБІЛЬШЕ.
 */

/** Коробка, у яку вміщається все до `limit` включно. */
const box = (limit: number) => (size: number) => size <= limit;

describe('largestFit', () => {
	it('знаходить найбільший розмір, що вміщається, а не перший-ліпший', () => {
		expect(largestFit(box(17.3), 11, 26)).toBe(17);
		expect(largestFit(box(17.5), 11, 26)).toBe(17.5);
	});

	it('не виходить за верхню межу, хоч місця й більше', () => {
		// «увага» в широкій кнопці не мусить ставати велетенською.
		expect(largestFit(box(100), 11, 26)).toBe(26);
	});

	it('не опускається нижче нижньої межі, навіть коли не вміщається нічого', () => {
		// Нижче за межу текст уже не прочитати; краще перенос, ніж крапки.
		expect(largestFit(box(5), 11, 26)).toBe(11);
	});

	it('рівно на межі вміщається', () => {
		expect(largestFit(box(11), 11, 26)).toBe(11);
		expect(largestFit(box(26), 11, 26)).toBe(26);
	});

	it('питає небагато: поділка в пів точки між 11 і 26 — це кілька кроків, а не тридцять', () => {
		let asked = 0;
		largestFit(
			(size) => {
				asked += 1;
				return size <= 19;
			},
			11,
			26
		);
		// Кожен крок — це вимір усіх кнопок віджета. Лінійний прохід дав би 31.
		expect(asked).toBeLessThanOrEqual(7);
	});

	it('перевернуті межі не зависають і не повертають сміття', () => {
		expect(largestFit(box(100), 26, 11)).toBe(26);
	});
});
