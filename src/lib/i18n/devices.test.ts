import { describe, expect, it } from 'vitest';
import { en } from './en';
import { uk } from './uk';

/**
 * «КОМПʼЮТЕР» І «ТЕЛЕФОН» — НЕ НАЗВИ РОЛЕЙ.
 *
 * Цей застосунок не про «керувати звуком на компʼютері з телефона». Грати може
 * будь-який пристрій, у якого є доступ до папки; керувати — будь-який інший;
 * а третій спосіб запуску взагалі без людини, за зовнішнім API. Щойно в тексті
 * зʼявляється «компʼютер», продукт у голові читача звужується до однієї пари
 * пристроїв — і саме так його потім і описують далі.
 *
 * Правило записане в PROJECT-CONTEXT § 1 ще з першого проходу термінології, і
 * його однаково порушили: нові рядки про адміністратора й про очікування пульта
 * приїхали з «компʼютером» усередині. Домовленість, яку ніщо не перевіряє,
 * тримається рівно до наступного рядка, тому тепер її перевіряє гейт.
 *
 * ЩО ТУТ ДОЗВОЛЕНО. Конкретний пристрій лишається там, де він СПРАВДІ
 * конкретний: «Chrome або Edge на компʼютері» — це про десктопний браузер, бо
 * доступу до папки в мобільному немає; «наведіть камеру телефона» — це про
 * камеру; «планшет у залі» — приклад, а не визначення ролі. Кожен такий випадок
 * названий поіменно нижче: список винятків має бути коротким і на очах.
 */

/** Ключі, де назва пристрою означає саме пристрій, а не роль. */
const CONCRETE = new Set([
	// Доступ до папки є лише в десктопних Chrome/Edge — це про браузер.
	'player.noSupport',
	// Камера — у телефона й планшета.
	'player.connectQrHint',
	// Приклад «де це знадобиться», а не опис ролі.
	'settings.startBoardLead'
]);

const DEVICE_WORDS =
	/(комп['ʼ’]?ютер|телефон|ноутбук|планшет|computer|laptop|desktop|\bphone\b|\btablet\b)/i;

describe('словник не звужує продукт до пари пристроїв', () => {
	it.each([
		['українською', uk],
		['англійською', en]
	])('%s', (_name, dictionary) => {
		const guilty = Object.entries(dictionary)
			.filter(([key]) => !CONCRETE.has(key))
			.filter(([, text]) => DEVICE_WORDS.test(text))
			.map(([key, text]) => `${key}: ${text}`);

		expect(guilty).toEqual([]);
	});
});
