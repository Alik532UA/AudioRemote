/**
 * ПЛАВНИЙ ПЕРЕХІД ГУЧНОСТІ ЕЛЕМЕНТА — секунда, і він ДОБІГАЄ КІНЦЯ ЗАВЖДИ.
 *
 * Різкий обрив звуку в залі чути як аварію: люди озираються на колонки. Те
 * саме з різким початком. Секунда — достатньо, щоб перехід читався як
 * рішення, і мало, щоб «стоп» лишався стопом. Число одне на всі переходи
 * навмисно: різна тривалість для паузи й стопа звучала б як несправність.
 *
 * ## ТАЙМЕР, А НЕ `requestAnimationFrame` — і це не смак, а справність
 *
 * Доти перехід тягнувся кадрами. У прихованій вкладці — і в закритій іншим
 * вікном: Chrome на Windows це відстежує — кадрів немає зовсім. А приймач
 * майже завжди у фоні: звукорежисер тримає поверх нього інше вікно. Заміряно в
 * справжньому браузері з прихованою вкладкою: наростання лишалося на нулі
 * (трек німий), а після «стоп» елемент грав далі — `paused: false`, час ішов,
 * — хоч прапорець `playing` уже впав і обидва екрани казали «зупинено».
 * «Пауза» не зупиняла так само, повтор після паузи між відтвореннями стартував
 * із нуля й лишався німим, тиша не глушила.
 *
 * Таймер у вкладці, що звучить, браузер не гальмує. Гучність рахується з
 * МИНУЛОГО ЧАСУ, а не накопичується кроками: хоч би як рідко приходив крок, він
 * ставить рівно те, що мало бути на цю мить. А окремий одноразовий таймер на
 * кінець секунди гарантує, що перехід ДОБІЖИТЬ, навіть коли кроки пригальмують
 * (тиха вкладка на повторі з нуля): у найгіршому випадку він стане різкішим,
 * але не безкінечним.
 *
 * ## Чому окремим файлом
 *
 * Перехід не знає нічого про треки, чергу й наміри — лише елемент, ціль і
 * «що зробити в кінці». У рушії він займав місце, якого там немає (файл під
 * стелею розміру), і перевірити його окремо від рушія було нічим.
 */

export const FADE_MS = 1000;

/** Сорок кроків на секунду: на слух так само плавно, як шістдесят кадрів. */
const STEP_MS = 25;

/**
 * Перевести гучність `element` до `target` за `FADE_MS` і покликати `done`.
 *
 * Гучність міняється на САМОМУ елементі: виставлена людиною гучність живе в
 * рушії, і перехід не має права її переписати — інакше після паузи повзунок
 * опинявся б на нулі.
 *
 * @returns скасування: зупиняє перехід там, де він є, і `done` НЕ кличе.
 */
export function fade(element: HTMLMediaElement, target: number, done?: () => void): () => void {
	const from = element.volume;
	const started = performance.now();
	let tick: ReturnType<typeof setInterval> | null = null;
	let end: ReturnType<typeof setTimeout> | null = null;

	const set = (share: number) => {
		element.volume = Math.max(0, Math.min(1, from + (target - from) * share));
	};
	const cancel = () => {
		if (tick !== null) clearInterval(tick);
		if (end !== null) clearTimeout(end);
		tick = null;
		end = null;
	};
	const finish = () => {
		cancel();
		set(1);
		done?.();
	};

	tick = setInterval(() => {
		const share = Math.min(1, (performance.now() - started) / FADE_MS);
		if (share >= 1) finish();
		else set(share);
	}, STEP_MS);
	end = setTimeout(finish, FADE_MS);

	return cancel;
}
