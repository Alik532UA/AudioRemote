/**
 * АРИФМЕТИКА ЧЕРГИ ПОВТОРІВ — окремо від рушія, бо саме вона тихо ламається.
 *
 * Смуга показує НЕ один прохід, а всю чергу разом із паузами: трек на три рази
 * з секундною паузою триває не три секунди, а одинадцять, і саме це має бути
 * видно й на плеєрі, і на пульті. Доти пульт доводив смугу до кінця за першим
 * відтворенням і далі стояв, хоч звук ішов ще двічі.
 *
 * Тут два перетворення, обидва зворотні одне одному:
 *
 * - `queueTotal` — скільки це триватиме разом;
 * - `queueSpot` — у яке відтворення (і в яке місце всередині нього) влучає
 *   позиція на смузі.
 *
 * Функції чисті навмисно. У рушії вони живуть поруч із `<audio>`, подіями й
 * таймерами, тобто перевірити їх там можна лише справжнім звуком і секундоміром
 * — а помилка тут буває на одиницю: зайва пауза в кінці, повтор, який
 * рахується з одиниці, влучання пальцем у тишу між повторами.
 */

/** Відтворення разом із паузою після нього. */
const unitOf = (clipMs: number, gapMs: number): number => clipMs + gapMs;

/**
 * Скільки триватиме вся черга.
 *
 * Пауз на одну менше, ніж відтворень: після останнього чекати нема чого. Це та
 * сама одиниця, на якій найлегше помилитися, — зайва пауза в кінці подовжила б
 * смугу рівно настільки, скільки триває тиша, якої не буде.
 */
export function queueTotal(clipMs: number, gapMs: number, plays: number): number {
	if (clipMs <= 0) return 0;
	const times = Math.max(1, Math.round(plays));
	return times * clipMs + (times - 1) * Math.max(0, gapMs);
}

export interface QueueSpot {
	/** Котре відтворення, рахуючи з нуля. */
	index: number;
	/** Скільки всередині нього, мс. */
	innerMs: number;
}

/**
 * Куди влучає позиція на смузі.
 *
 * Влучання в ПАУЗУ притискається до кінця звуку: пауза — це тиша, і лишати
 * палець посеред неї означало б «нічого не сталося». Позиція за межами черги
 * притискається до останнього відтворення.
 */
export function queueSpot(
	positionMs: number,
	clipMs: number,
	gapMs: number,
	plays: number
): QueueSpot {
	const times = Math.max(1, Math.round(plays));
	const unit = unitOf(clipMs, Math.max(0, gapMs));
	if (unit <= 0) return { index: 0, innerMs: 0 };

	const at = Math.max(0, positionMs);
	const index = Math.min(times - 1, Math.floor(at / unit));
	const innerMs = Math.max(0, Math.min(clipMs, at - index * unit));

	return { index, innerMs };
}
