import { describe, expect, it } from 'vitest';
import { queueSpot, queueTotal } from './queue';

/** Трисекундний трек, тричі, з паузою в секунду: 3×3000 + 2×1000. */
const CLIP = 3000;
const GAP = 1000;

describe('скільки триватиме черга', () => {
	it('без повторів — це сам трек', () => {
		expect(queueTotal(CLIP, GAP, 1)).toBe(CLIP);
	});

	it('пауз на одну менше, ніж відтворень', () => {
		// Зайва пауза в кінці подовжила б смугу на тишу, якої не буде.
		expect(queueTotal(CLIP, GAP, 3)).toBe(11_000);
	});

	it('без паузи — просто помножено', () => {
		expect(queueTotal(CLIP, 0, 4)).toBe(12_000);
	});

	it('доки тривалість невідома, черги теж немає', () => {
		// Браузер повідомляє тривалість не одразу, і нуль тут чесніший за
		// вигадане число: смуга не має стрибати від «0:11» до «0:00» і назад.
		expect(queueTotal(0, GAP, 3)).toBe(0);
	});
});

describe('куди влучає позиція на смузі', () => {
	const spot = (at: number) => queueSpot(at, CLIP, GAP, 3);

	it('початок — перше відтворення', () => {
		expect(spot(0)).toEqual({ index: 0, innerMs: 0 });
	});

	it('середина смуги — середина ДРУГОГО відтворення', () => {
		// 5500 = одна одиниця (4000) плюс півтори секунди всередині.
		expect(spot(5500)).toEqual({ index: 1, innerMs: 1500 });
	});

	it('влучання в паузу притискається до кінця звуку', () => {
		/*
		 * 3500 — це тиша між першим і другим. Лишити палець там означало б
		 * «нічого не сталося»: звук почався б аж за пів секунди, і виглядало б це
		 * як кнопка, що не працює.
		 */
		expect(spot(3500)).toEqual({ index: 0, innerMs: CLIP });
	});

	it('за межами черги — кінець останнього відтворення', () => {
		expect(spot(999_999)).toEqual({ index: 2, innerMs: CLIP });
	});

	it('відʼємна позиція — початок', () => {
		expect(spot(-5000)).toEqual({ index: 0, innerMs: 0 });
	});

	it('без тривалості нема куди влучати', () => {
		expect(queueSpot(1000, 0, 0, 3)).toEqual({ index: 0, innerMs: 0 });
	});
});
