import { describe, expect, it } from 'vitest';
import { folderOf } from './source';

describe('підпапка треку', () => {
	it('трек із кореня не має папки', () => {
		expect(folderOf('Гонг.mp3')).toBe('');
	});

	it('одна ланка — назва підпапки', () => {
		expect(folderOf('тривога/Відбій.mp3')).toBe('тривога');
	});

	it('глибша вкладеність лишається цілою', () => {
		/*
		 * Не остання ланка, а весь шлях: дві підпапки «сирена» в різних наборах —
		 * це два різні місця, і показані однаково вони злилися б в одне.
		 */
		expect(folderOf('тривога/сирена/Довга.mp3')).toBe('тривога/сирена');
	});

	it('скісна риска на початку не робить папки з порожнім іменем', () => {
		expect(folderOf('/Гонг.mp3')).toBe('');
	});
});
