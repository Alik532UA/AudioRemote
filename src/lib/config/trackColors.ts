/**
 * ДЕСЯТЬ ЗАГОТОВОК КОЛЬОРУ ДЛЯ ТРЕКІВ.
 *
 * ## Навіщо колір
 *
 * Список на сотню назв у темному залі читають не читаючи: шукають очима те, що
 * впізнають. Колір робить трек упізнаваним швидше за будь-яку назву — і саме
 * тому він стоїть смугою збоку, а не десь у властивостях.
 *
 * ## Чому заготовки, а не вибір кольору
 *
 * Палітра з піпеткою дасть рожевий на рожевому й сірий, якого не видно. Десять
 * готових кольорів вибрати неможливо неправильно, а `<input type="color">` на
 * телефоні ще й відкриває системне вікно, у якому людина застрягає.
 *
 * ## Чому один колір на обидві теми, а не пара
 *
 * Кожен узятий середньотоновим навмисно: він мусить читатися і на білій картці,
 * і на #121927. Пара «світлий/темний» подвоїла б перелік і дала б два джерела
 * одного рішення; натомість колір тут ніколи не є ТЛОМ під текстом — він
 * смуга збоку плюс ледь помітна підкладка через `color-mix`.
 *
 * ## Чому в базі лежить назва, а не код кольору
 *
 * Назва — це посилання на цей перелік, тобто палітру можна підправити однією
 * правкою тут, і всі дошки поїдуть за нею. Код кольору в базі заморозив би
 * вчорашню палітру назавжди. Крім того, коротка назва легко перевіряється
 * правилом бази — а довільний рядок кольору ні.
 */

export interface TrackColor {
	/** Що лежить у базі. Лише малі латинські літери — так вимагає правило. */
	slug: string;
	/** Середньотоновий колір, читабельний на обох темах. */
	hex: string;
}

export const TRACK_COLORS: readonly TrackColor[] = [
	{ slug: 'ruby', hex: '#d64550' },
	{ slug: 'coral', hex: '#e07a3f' },
	{ slug: 'amber', hex: '#c9961e' },
	{ slug: 'olive', hex: '#8aa33c' },
	{ slug: 'emerald', hex: '#35a06b' },
	{ slug: 'teal', hex: '#2a9d9a' },
	{ slug: 'azure', hex: '#3b8fd4' },
	{ slug: 'indigo', hex: '#6b74d6' },
	{ slug: 'violet', hex: '#9a5fd0' },
	{ slug: 'rose', hex: '#d45f95' }
];

/**
 * Колір за назвою. Невідома назва — це «без кольору», а не помилка: дошку могла
 * пофарбувати новіша збірка, і рядок, якого ми не знаємо, краще показати сірим,
 * ніж не показати трек узагалі.
 */
export function colorOf(slug: string | undefined | null): string | null {
	if (!slug) return null;
	return TRACK_COLORS.find((color) => color.slug === slug)?.hex ?? null;
}

/** Порядковий номер кольору, з одиниці — для підпису читалці. */
export function colorNumber(slug: string): number {
	return TRACK_COLORS.findIndex((color) => color.slug === slug) + 1;
}
