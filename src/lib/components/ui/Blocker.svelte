<script lang="ts">
	import { IconWarning } from '$lib/config/icons';

	/**
	 * ЕКРАН, НА ЯКОМУ НЕМАЄ ЩО НАТИСКАТИ, — ПЕРЕКРИТИЙ.
	 *
	 * ## Чому не рядок у списку
	 *
	 * Коли дошку на пристрої, що грає, закрито, кнопки лишаються, і жодна з них
	 * нічого не робить. Доти про це казав напис у колонці — і на телефоні він
	 * опинявся ПІД списком: при семи віджетах до нього треба домотати. Тобто
	 * людина бачила робочий на вигляд пульт, тиснула, нічого не діялося, і
	 * пояснення лежало там, куди вона не дивилася.
	 *
	 * Тому це перекриття: якщо доступ однаково ні до чого не веде, давати його
	 * означає обіцяти те, чого немає.
	 *
	 * ## Шапку НЕ перекриваємо — інакше це пастка
	 *
	 * У шапці лежить єдиний вихід: знак застосунку, «назад» і налаштування.
	 * Перекриття, що накриває і її, лишає людину на екрані, з якого немає куди
	 * піти, — і це гірше за той дефект, який ми лікуємо.
	 *
	 * Зроблено шаром, а не `<dialog>` із `showModal()`: той кладе вікно у
	 * верхній шар над УСІМ, включно з шапкою, і робить решту сторінки інертною
	 * цілком. Тут навпаки — шар стоїть НИЖЧЕ смуги застосунку (`z-index`), тож
	 * вона лишається видимою й натискною, а все під нею накрите.
	 *
	 * ## Клавіатура теж мусить упертися
	 *
	 * Сам по собі шар ловить лише мишу й палець: `Tab` спокійно проходить крізь
	 * нього у кнопки, яких не видно. Тому сторінка, що ставить це перекриття,
	 * позначає перекритий вміст `inert` — тоді туди не потрапляє ні фокус, ні
	 * читалка.
	 */
	interface Props {
		/** Локатор шару. Текст усередині дістає той самий із суфіксом `-text`. */
		testid: string;
		text: string;
	}

	let { testid, text }: Props = $props();
</script>

<!--
	`role="alert"`: напис зʼявляється не за бажанням людини, а тому, що зникло
	щось на іншому пристрої. Читалка мусить сказати це одразу, а не тоді, коли
	до шару дійде черга.
-->
<div class="blocker" data-testid={testid}>
	<p class="blocker__card card" role="alert">
		<IconWarning size={22} aria-hidden="true" />
		<span data-testid="{testid}-text">{text}</span>
	</p>
</div>

<style>
	.blocker {
		/*
		 * `fixed`, а не `absolute`: шар мусить накрити видиме ВІКНО, а не блок,
		 * усередині якого стоїть, — інакше на довгому списку він прокручується
		 * геть разом із тим, що перекриває.
		 *
		 * `z-index` нижчий за смугу застосунку (у неї 20): саме це й лишає
