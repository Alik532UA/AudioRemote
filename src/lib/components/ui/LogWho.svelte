<script lang="ts">
	/**
	 * ЧИЯ ЦЕ РУКА — одна мітка на обидва журнали.
	 *
	 * ## Що тут було не так
	 *
	 * Журнали аудіодошки й інфодошки відповідали на це питання по-різному, і
	 * жоден із двох не відповідав повністю. Аудіо показував РОЛЬ і мав гілку
	 * для підпису, яка не виконувалася ніколи: пульт підпису не надсилав узагалі.
	 * Інфодошка показувала ПІДПИС, а замість ролі — «сам» на власних діях, тобто
	 * мітку з іншої осі: «сам» відповідає на «чия сторона», а «Оля» — на «хто
	 * саме», і поруч вони читалися як дві відповіді на одне питання.
	 *
	 * Тепер вісь одна: спершу СТОРОНА (вона є завжди), потім ІМʼЯ (коли назвався).
	 * Мітка без імені лишається такою ж короткою, як була.
	 *
	 * ## Чому одна мітка, а не дві поруч
	 *
	 * Журнал читають на телефоні, де рядок і так переносить назву треку. Дві
	 * окремі плашки забирали б удвічі більше ширини на відповідь, яка тут друга
	 * за важливістю: головне в рядку — ЩО сталося.
	 */
	interface Props {
		/** Сторона, уже перекладена: «плеєр», «пульт», «табло», «помічник», «за API». */
		side: string;
		/** Як підписався той, хто натиснув. Порожньо — не називався. */
		name?: string;
		/**
		 * Звідки дія, для кольору. `own` — цей самий пристрій, `api` — без людини.
		 * Колір тут лише допомагає оку; саму відповідь несе текст.
		 */
		tone: 'own' | 'remote' | 'api';
		testid: string;
	}

	let { side, name = '', tone, testid }: Props = $props();

	const shown = $derived(name.trim());
</script>

<span class="who who--{tone}" data-testid={testid}>
	{side}{#if shown}<span class="who__name">· {shown}</span>{/if}
</span>

