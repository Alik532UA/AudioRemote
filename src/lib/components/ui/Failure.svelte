<script lang="ts">
	import CopyButton from './CopyButton.svelte';
	import { FIX_COMMAND } from '$lib/net/describeError';
	import { t, type TranslationKey } from '$lib/i18n/i18n.svelte';

	/**
	 * ВІДМОВА, ЯКА КАЖЕ, ЩО РОБИТИ — І ДАЄ ЦЕ ЗРОБИТИ.
	 *
	 * ## Навіщо окремий компонент
	 *
	 * Той самий текст показують три різні місця: сторінка плеєра (де відмова
	 * ФАТАЛЬНА — на екрані більше нічого), форма підключення (де вона стоїть під
	 * полями) і смуга неполадки на дошці. Доти кожне малювало `<p class="error">`
	 * саме, і наслідків було два.
	 *
	 * Перший видно на екрані: фатальна відмова виглядала як рядок червоного
	 * тексту вгорі ліворуч над порожньою сторінкою. Людина, у якої не піднявся
	 * емулятор, бачила не «ось що сталося і ось що робити», а схоже на збій
	 * розмітки.
	 *
	 * Другий не видно взагалі: частина порад містить КОМАНДУ, і команду цю
	 * доводилося виділяти мишею з речення. `npm run emulators` посеред рядка —
	 * це не інструкція, це домашнє завдання.
	 *
	 * ## Чому ключ, а не готовий текст
	 *
	 * Сторінки писали `failure = t(describeError(error))` — тобто перекладали
	 * ОДРАЗУ й запамʼятовували результат. Текст застигав мовою, яка була на
	 * момент відмови, і перемикання мови його не чіпало. Та сама помилка вже
	 * лікувалася в опитувачі тригерів (`FAULT_TEXT` у `watcher.svelte.ts`): там
	 * теж зберігається ключ, а перекладає той, хто показує.
	 *
	 * ## `block`
	 *
	 * `false` — рядок під полем, там де поруч є форма й контекст. `true` —
	 * фатальна відмова: по центру, з полем команди, бо на екрані більше нічого
	 * немає й читати це буде людина, яка щойно нічого не зрозуміла.
	 */

	interface Props {
		/** Ключ повідомлення. Саме ключ: перекладає той, хто показує. */
		reason: TranslationKey;
		/** Фатальна відмова на всю сторінку, а не рядок під полем. */
		block?: boolean;
		testid?: string;
	}

	let { reason, block = false, testid }: Props = $props();

	const command = $derived(FIX_COMMAND[reason]);
</script>

<div class="fail" class:fail--block={block} role="alert" data-testid={testid}>
	<p class="fail__text">{t(reason)}</p>

	{#if command}
		<!--
			Команда — в полі з моноширинним шрифтом і кнопкою копіювання, а не
			посеред речення. Її треба ВСТАВИТИ в термінал, а не прочитати.
		-->
		<div class="fail__cmd">
			<code class="mono fail__cmdText" data-testid="fail-command-value">{command}</code>
			<CopyButton value={command} label={command} testid="copy-command" />
		</div>
	{/if}
</div>

<style>
	.fail {
		display: flex;
		flex-direction: column;
		gap: var(--gap-sm);
	}

	.fail__text {
		margin: 0;
		color: var(--danger);
	}

	/*
	 * ФАТАЛЬНА ВІДМОВА СТОЇТЬ ПО ЦЕНТРУ, і це не декор.
	 *
	 * Коли сторінка порожня, текст при лівому верхньому куті читається як
	 * уламок розмітки: очі шукають вміст, якого немає, і знаходять рядок, що
	 * ні до чого не прикріплений. Те саме речення в центрі читається як
	 * відповідь на питання «а де все».
	 *
	 * `60ch` — щоб рядок не тягнувся на весь монітор: порада, яку доводиться
	 * читати очима зліва направо через півтора метра, не порада.
	 */
	.fail--block {
		align-items: center;
		justify-content: center;
		gap: var(--gap);
		/*
		 * Висота — щоб блок стояв у СЕРЕДИНІ порожнечі, а не притискався до
		 * шапки. Сторінка при фатальній відмові порожня повністю, і повідомлення
		 * під самим верхом читається як підпис до шапки, а не як відповідь на
		 * питання «а де все».
		 *
		 * `dvh`, а не `vh`: на телефоні панель браузера з'їдає частину вікна, і
		 * `vh` рахує ту висоту, якої на екрані немає (FLUID-SIZING-v9 § 2).
		 * Половина — а не весь екран: нижче лишається місце, і блок не скаче,
		 * коли панель ховається.
		 */
		min-block-size: 50dvh;
		max-width: 60ch;
		margin-inline: auto;
		padding: var(--gap-lg) var(--gap);
		text-align: center;
	}

	.fail__cmd {
		display: flex;
		align-items: center;
		gap: var(--gap-sm);
		padding: var(--gap-sm) var(--gap-sm) var(--gap-sm) var(--gap);
		border: 1px solid var(--border);
		border-radius: var(--radius-sm);
		background: var(--bg-sunken);
	}

	.fail__cmdText {
		/* Довга команда переноситься, а не розсуває вікно. */
		overflow-wrap: anywhere;
		text-align: start;
	}
</style>
