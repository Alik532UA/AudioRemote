<script lang="ts">
	import { asset } from '$app/paths';

	interface Props {
		size?: number;
	}

	let { size = 32 }: Props = $props();

	/**
	 * ЗНАК ЗАСТОСУНКУ — ФАЙЛ, а не намальований поруч SVG.
	 *
	 * Логотип у проєкту вже є: помаранчевий квадрат, який лежить на робочому
	 * столі, у вкладці браузера й на телефоні серед інших застосунків. Саме його
	 * людина й упізнає. Знак у шапці, намальований окремо, упізнаванню не
	 * допомагав зовсім: у шапці одне, на смужці задач інше, і жодне з двох не
	 * закріплювалося.
	 *
	 * Ціна названа: файл не міняє кольору разом із темою. Для квадратного
	 * логотипа це не втрата — він однаково має власне тло, і саме таким його
	 * бачать в усіх інших місцях.
	 *
	 * `asset()`, а не `/favicon.png`: на GitHub Pages сайт лежить під
	 * `/AudioRemote/`, і абсолютний шлях від кореня вів би на чужий проєкт.
	 *
	 * SVG НИЖЧЕ ЛИШЕНО НАВМИСНО й не показується. Це не забутий код: він єдине
	 * місце, де знак існує в кольорі теми, і знадобиться, щойно зʼявиться
	 * потреба в одноколірному знаку — у листі, на друку, у вузькій смузі. Умова
	 * стала, а не прапорець: вибору тут немає, є запас.
	 */
	const USE_FILE = true;

	/**
	 * ЧОМУ КОЛИСЬ БУВ ІНЛАЙНОВИЙ SVG, а не `<img src="favicon.png">`.
	 *
	 * Причина одна, і вона про теми: знак у шапці мусить бути видно і на світлому
	 * тлі, і на темному. Файл значка — помаранчевий квадрат із власним градієнтом
	 * (він же лягає на робочий стіл, де тла застосунку немає), і в шапці він
	 * виглядав би наліпкою, а не частиною сторінки.
	 *
	 * Тут усе бере `currentColor`, а хвилі — ще й прозорість. Спершу вони були
	 * пофарбовані в `--accent`, але в цій палітрі акцент майже збігається з
	 * кольором тексту (`#cbd5e1` на темній), тож двоколірність не читалася зовсім.
	 * У самому логотипі хвилі не іншого кольору, а БЛІДІШІ за повзунки — і саме
	 * це відтворює прозорість, причому однаково в обох темах.
	 *
	 * ФОРМА — ТА САМА, ЩО В `src-tauri/icons/source.png`: три вертикальні
	 * повзунки з кульками й дві хвилі над ними. Доти тут був трикутник «грати» й
	 * хвилі — геометрія заглушки, яку малював `scripts/make-icons.mjs`, поки в
	 * проєкту не було справжнього значка. Значок зʼявився, і знак поїхав за ним:
	 * розходження тут читається як два різні застосунки.
	 *
	 * Що НЕ перенесено з файлу навмисно: рамка-квадрат, градієнт і кільця
	 * всередині кульок. На 26 пікселях у шапці вони перетворюються на кашу, а
	 * квадрат ще й додає другу рамку до кнопки, у якій знак стоїть.
	 */
</script>

