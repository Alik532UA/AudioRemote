import { normalizeBoardId, normalizePassword } from './secret';

/**
 * АДРЕСА ДОШКИ В БАЗІ — і чому пароль мусить бути саме тут.
 *
 * ## Головне
 *
 * Правила Firebase — єдина межа безпеки: публічний конфіг лежить у бандлі, тож
 * будь-хто може звернутися до бази тим самим SDK із консолі браузера, повз наш
 * інтерфейс. А правила вміють дивитися лише на auth і на ШЛЯХ — передати їм
 * «пароль, який я щойно ввів» неможливо.
 *
 * Звідси єдина форма, у якій пароль є межею, а не прикрасою: **пароль входить
 * в адресу**. Дошка живе за шляхом boards/{hex}, де hex — хеш від пари
 * (ідентифікатор, пароль). Неправильний пароль дає інший хеш, тобто адресу, за
 * якою нічого немає, — і відмовляє тут база, а не наш if.
 *
 * Перелічити boards правила забороняють: дозвіл читати стоїть лише на
 * конкретній дошці, тож зібрати список хешів теж не можна.
 *
 * ## Що з цього випливає й названо прямо
 *
 * - **У базі немає ні ідентифікатора, ні пароля, ні їхніх частин.** Вивантажена
 *   база не каже навіть, як дошки називаються.
 * - **Зміна пароля = переїзд дошки** на нову адресу. Це не побічний ефект, це та
 *   сама властивість з іншого боку, і інтерфейс мусить казати про це прямо.
 * - **Відкликати доступ окремій людині не можна.** Хто знає пару — той усередині.
 *   Це свідоме спрощення: відкликання коштувало б окремого механізму вступу
 *   через вузол-браму, і на нього тут не пішли.
 * - **Права підвищуються другим паролем, а не списком людей.** Адміністратор —
 *   це той, хто знає ще один пароль, і знання це перевіряється так само: другим
 *   ключем, виведеним тим самим способом (`deriveAdminKey`). Списку тих, кому
 *   можна, не існує — отже й підтримувати його не треба.
 * - **Запас тримається на паролі.** Згенерований дає близько 37 біт
 *   (passwordEntropyBits); перевірити здогад можна лише мережевим читанням,
 *   тобто перебір іде зі швидкістю мережі, а не процесора.
 *
 * ## Потрібен захищений контекст
 *
 * crypto.subtle існує лише в secure context (https або localhost). Це не
 * обмеження цього модуля: дескриптори теки (File System Access) вимагають того
 * самого. Тобто відкрити застосунок по http://192.168.x.x не вийде в будь-якому
 * разі, і краще сказати це одним зрозумілим рядком, ніж упасти на undefined.
 */

/**
 * Версія схеми виведення. Змінюється разом із будь-якою зміною нормалізації або
 * формату рядка нижче: без неї дошки, створені старою збіркою, тихо переїхали б,
 * а люди побачили б «дошку не знайдено» без жодної причини.
 */
const SCHEME = 'AudioRemote/v1';

/**
 * Довжина ключа в шістнадцяткових символах. 32 символи — 128 біт.
 *
 * Обрізання не послаблює нічого: запас і так обмежений паролем (близько 37
 * біт), а 128 біт унеможливлюють випадковий збіг двох різних дощок.
 */
const KEY_HEX_LENGTH = 32;

export class InsecureContextError extends Error {
	constructor() {
		super('crypto.subtle недоступний: потрібне https або localhost');
		this.name = 'InsecureContextError';
	}
}

export class EmptySecretError extends Error {
	constructor(what: 'id' | 'password') {
		super(what === 'id' ? 'порожній ідентифікатор дошки' : 'порожній пароль');
		this.name = 'EmptySecretError';
	}
}

/**
 * АДРЕСУ КАНАЛУ ПОПРОСИЛИ ВИВЕСТИ НЕ З ТОГО.
 *
 * `deriveAdminKey` бере АДРЕСУ дошки (32 шістнадцяткові символи), а поруч із
 * нею в кожному місцевому записі лежить `id` — той, що диктують уголос. Обидва
 * поля — рядки, тож переплутати їх компілятор не заважає ніяк, а наслідок
 * мовчазний: інший хеш, тобто адреса, за якою нічого немає.
 *
 * Заміряно: саме так і було в двох місцях із чотирьох — у кнопці видалення
 * дошки й у прибиранні прострочених. Канал відкривався за ключем, а
 * закривався за ідентифікатором, тож `remove` бив у порожнечу; правило
 * «знести може лише господар» бачило порожнечу без господаря й ВІДМОВЛЯЛО —
 * і через відмову не видалялася вже й сама дошка.
 */
export class NotABoardKeyError extends Error {
	constructor(given: string) {
		super(`очікувалася адреса дошки з 32 шістнадцяткових символів, а не «${given}»`);
		this.name = 'NotABoardKeyError';
	}
}

/** Вивести ключ дошки з ідентифікатора й пароля. */
export async function deriveBoardKey(rawId: string, rawPassword: string): Promise<string> {
	const id = normalizeBoardId(rawId);
	const password = normalizePassword(rawPassword);

	if (!id) throw new EmptySecretError('id');
	if (!password) throw new EmptySecretError('password');

	return derive([SCHEME, id, password]);
}

/**
 * АДРЕСА АДМІНСЬКОГО КАНАЛУ — той самий прийом, що й з паролем дошки.
 *
 * Адміністратор — це третя роль: пульт, який міняє налаштування дошки так само,
 * як людина за самим комп'ютером. Пароль у нього окремий, і причина та сама, що
 * й для пароля дошки: правила бази вміють дивитися лише на auth і на ШЛЯХ, тож
 * «перевірити пароль» вони не можуть — пароль мусить БУТИ шляхом.
 *
 * Тому адмінський канал живе НЕ всередині дошки, а окремою гілкою `admin`.
 * Усередині дошки сховати його неможливо: дозвіл читати стоїть на `boards/$key`
 * і поширюється на все піддерево, тобто будь-хто з паролем дошки прочитав би й
 * адресу каналу — і тим самим отримав би права адміністратора.
 *
 * Ключ виводиться з АДРЕСИ ДОШКИ, а не з пари (ідентифікатор, пароль): так
 * канал прив'язаний до конкретної дошки, і зміна пароля дошки забирає з собою
 * й адмінський доступ — що правильно, бо це вже інша дошка.
 *
 * Зворотний бік названий прямо: з адреси каналу адресу дошки не вивести, тож
 * сам собою канал нікуди не пускає — адміністратор спершу заходить пультом, як
 * звичайна людина, і лише потім підвищує собі права.
 */
export async function deriveAdminKey(boardKey: string, rawPassword: string): Promise<string> {
	/*
	 * ПЕРШИЙ АРГУМЕНТ — АДРЕСА, А НЕ ІДЕНТИФІКАТОР, і перевіряється це тут.
	 *
	 * Обидва поля лежать поруч у кожному місцевому записі й обидва — рядки, тож
	 * компілятор їх не розрізняє. Помилка при цьому не падає нікуди: виходить
	 * просто ІНШИЙ хеш, тобто адреса, за якою нічого немає. Саме так і сталося
	 * у двох місцях із чотирьох — див. `NotABoardKeyError`.
	 *
	 * Форми не перетинаються: ідентифікатор — пʼять символів із верхнього
	 * регістру без `0`, `1` та `I`, ключ — тридцять два шістнадцяткові.
	 *
	 * Форма береться в `isBoardKey`, а не переписується сюди: переписана, вона
	 * розійшлася б із `KEY_HEX_LENGTH` мовчки — те саме, про що попереджає сам
	 * `isBoardKey`.
	 */
	if (!isBoardKey(boardKey)) throw new NotABoardKeyError(boardKey);

	const password = normalizePassword(rawPassword);
	if (!password) throw new EmptySecretError('password');

	return derive([SCHEME, 'admin', boardKey, password]);
}

/**
 * Спільне виведення: SHA-256 від частин, склеєних нуль-символом.
 *
 * Роздільник — саме нуль-символ: нормалізовані значення складаються з літер,
 * цифр і дефіса, тож він не може трапитися в жодному з них. Без роздільника,
 * якого неможливо підробити, пара (AB, CD-EF) і пара (ABCD, EF) дали б один
 * рядок — і дві різні дошки опинилися б за однією адресою.
 */
async function derive(parts: string[]): Promise<string> {
	const subtle = globalThis.crypto?.subtle;
	if (!subtle) throw new InsecureContextError();

	const material = parts.join('\u0000');
	const digest = await subtle.digest('SHA-256', new TextEncoder().encode(material));

	return [...new Uint8Array(digest)]
		.map((byte) => byte.toString(16).padStart(2, '0'))
		.join('')
		.slice(0, KEY_HEX_LENGTH);
}

/**
 * Чи схоже це на адресу дошки.
 *
 * Потрібне там, де ключ приходить ЗЗОВНІ, — у посиланні на пульт. Довжина
 * береться звідси, а не переписується в місці виклику: переписана, вона
 * розійшлася б із `KEY_HEX_LENGTH` мовчки, і посилання перестало б працювати
 * без жодного сліду (саме так і сталося з першою спробою — там стояло 64).
 */
export const isBoardKey = (value: string): boolean =>
	new RegExp(`^[0-9a-f]{${KEY_HEX_LENGTH}}$`).test(value);

/** Шлях до вузла дошки в Realtime Database. */
export function boardPath(key: string): string {
	return `boards/${key}`;
}

/** Шлях до адмінського каналу. Гілка окрема — див. `deriveAdminKey`. */
export function adminPath(key: string): string {
	return `admin/${key}`;
}
