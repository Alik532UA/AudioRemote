import { readJson, writeJson } from '$lib/services/storage';

export type BoardRole = 'player' | 'remote';

/**
 * ЩО САМЕ ЗА ДОШКА — звук чи підказки.
 *
 * Роль і вид — різні питання, і плутати їх не можна. РОЛЬ каже, що робить цей
 * пристрій: приймає чи керує. ВИД каже, чим саме вони обмінюються: аудіодошка
 * грає файли з папки, інфодошка показує, що попросили натисканням.
 *
 * Механіка підключення в них спільна цілком — адреса виводиться з пари
 * (ідентифікатор, пароль), присутність, журнал команд із квитанцією,
 * прибирання покинутих. Різні лише дані всередині дошки й екрани.
 *
 * Назви ролей лишаються ті самі й у другому виді: `player` — той, хто приймає
 * і володіє дошкою, `remote` — той, хто керує. На екрані вони звуться інакше
 * («плеєр» і «пульт» у звуку, «табло» і «підказка» в інфодошці), але питання
 * «хто господар» те саме, і правила бази теж.
 *
 * ЗАПИСИ БЕЗ ЦЬОГО ПОЛЯ — АУДІО. Дошки, збережені до появи другого виду, поля
 * не мають; читати їх як «невідомо» означало б викинути людину з її ж дошки
 * після оновлення застосунку.
 */
export type BoardKind = 'audio' | 'info';

/** Вид дошки із запису, який міг бути створений до появи видів. */
export const kindOf = (board: { kind?: BoardKind }): BoardKind => board.kind ?? 'audio';

/**
 * Вид дошки з адреси сторінки: `?kind=info`.
 *
 * Сторінки створення й підключення в обох видів ті самі: ідентифікатор,
 * пароль, ентропія, QR — усе це однакове, і другий примірник цих форм
 * розійшовся б із першим на першій же правці. Різниця лише в тому, куди вести
 * далі, і саме її несе адреса.
 *
 * Усе, що не `info`, — звук: чуже чи зіпсуте значення мусить давати типову
 * дошку, а не порожній екран.
 */
export const kindFromSearch = (search: string): BoardKind =>
	new URLSearchParams(search).get('kind') === 'info' ? 'info' : 'audio';

export interface SavedBoard {
	/** Адреса дошки в базі — хеш від пари (ідентифікатор, пароль). */
	key: string;
	/** Ідентифікатор, як його показують людині. */
	id: string;
	/** Назва, яку дала людина. Порожня — покажемо ідентифікатор. */
	name: string;
	role: BoardRole;
	/** Звук чи підказки. Немає — дошка створена до появи видів, тобто аудіо. */
	kind?: BoardKind;
	/**
	 * Пароль — ЛИШЕ для дощок, які створені тут.
	 *
	 * Ключа досить, щоб зайти, тож для підключення пароль не потрібен і не
	 * зберігається. Але господар мусить мати змогу продиктувати його завтра, а
	 * відновити з хеша неможливо за побудовою — отже або зберігати, або людина
	 * втрачає власну дошку через тиждень.
	 *
	 * Ризик названо: хто має доступ до цього браузера, той бачить пароль. Він і
	 * так має `key`, тобто вже всередині, — тобто зберігання пароля не відкриває
	 * нічого нового, а лише робить видимим те, що вже доступне.
	 */
	password?: string;
	/**
	 * ДРУГИЙ ПАРОЛЬ — той, що дає право міняти налаштування з пульта.
	 *
	 * Зберігається з тієї самої причини, що й перший: його диктують уголос
	 * новому адміністраторові, а відновити з хеша неможливо за побудовою.
	 * Ризик той самий і не більший — хто має доступ до цього браузера, той
	 * сидить за самим плеєром, тобто вже може все.
	 *
	 * Порожньо — адміністратора в цієї дошки немає взагалі, і канал не
	 * відкритий. Це типовий стан: третя роль потрібна не кожному залу.
	 */
	adminPassword?: string;
	/** Коли востаннє відкривали. Список сортується за цим. */
	at: number;
}

const STORAGE_KEY = 'boards';
/**
 * Скільки ЧУЖИХ дощок тримати в списку. Далі найстаріші випадають.
 *
 * СВОЇХ це не стосується, і різниця тут не в зручності. Місцевий запис — ЄДИНЕ
 * місце, де живе адреса власної дошки: `boards` не перелічується за побудовою,
 * а відновити адресу з пароля можна лише знаючи ще й ідентифікатор. Тобто
 * запис, що випав зі списку, означав не «дошки немає в меню», а «дошки більше
 * не знайде ніхто, і знести її теж не зможе ніхто» — покинутий вузол у базі
 * назавжди.
 *
 * Створити тринадцяту дошку легко: кожен захід із новою парою — нова дошка.
 * Тож це не гіпотетичний випадок.
 *
 * Чужі (пульт) витісняти можна: там немає ні пароля, ні права видаляти, а
 * адресу однаково продиктують заново.
 */
const LIMIT = 12;

export function listBoards(): SavedBoard[] {
	return readJson<SavedBoard[]>(STORAGE_KEY, [])
		.filter((board) => typeof board?.key === 'string' && board.key.length > 0)
		.sort((left, right) => right.at - left.at);
}

/**
 * Запам'ятати дошку. Той самий `key` оновлюється, а не дублюється.
 *
 * `key` — природний ідентифікатор запису: дві дошки з однаковою адресою це та
 * сама дошка, навіть якщо людина дала їй іншу назву.
 */
export function rememberBoard(board: Omit<SavedBoard, 'at'>): void {
	const rest = listBoards().filter((saved) => saved.key !== board.key);
	const next = [{ ...board, at: Date.now() }, ...rest];

	/*
	 * Витісняємо лише ЧУЖІ. Доти `slice(0, LIMIT)` різав усе поспіль, і разом
	 * із тринадцятим записом зникала єдина в світі адреса власної дошки — див.
	 * докблок до `LIMIT`.
	 *
	 * Порядок зберігається такий, яким був: список сортує `listBoards()` за
	 * часом, а тут ми лише прибираємо зайве, не переставляючи решту.
	 */
	const isMine = (saved: SavedBoard): boolean => Boolean(saved.password);
	let quota = LIMIT;
	const kept = next.filter((saved) => {
		if (isMine(saved)) return true;
		quota -= 1;
		return quota >= 0;
	});

	writeJson(STORAGE_KEY, kept);
}

export function forgetBoard(key: string): void {
	writeJson(
		STORAGE_KEY,
		listBoards().filter((board) => board.key !== key)
	);
}

export function findBoard(key: string): SavedBoard | null {
	return listBoards().find((board) => board.key === key) ?? null;
}
