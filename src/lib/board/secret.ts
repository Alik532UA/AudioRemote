import { WORDS } from './words';

/**
 * ІДЕНТИФІКАТОР ДОШКИ Й ПАРОЛЬ — те, що людина каже вголос.
 *
 * ## Чому нормалізація тут найважливіша функція в застосунку
 *
 * Адреса дошки в базі — це хеш від пари (ідентифікатор, пароль). Отже той, хто
 * створює, і той, хто підключається, мусять отримати БАЙТ У БАЙТ той самий
 * рядок — інакше хеші розійдуться, і дошка просто «не знайдеться». Помилка тут
 * не має жодного симптому, крім найгіршого з можливих: людина впевнена, що
 * ввела правильно, і вона таки ввела правильно.
 *
 * Тому нормалізація прибирає рівно ті розбіжності, які виникають у житті:
 *
 * | Що стається | Що робить нормалізація |
 * |---|---|
 * | «кава» / «КАВА» / «Кава» | верхній регістр |
 * | «КАВА ВІКНО» / «КАВА-ВІКНО» / «КАВА_ВІКНО» | будь-який розділювач → один `-` |
 * | зайві пробіли з копіювання | обрізання й згортання |
 * | «ї» одним символом або «і»+діакритика | NFC |
 * | латинська `A` замість кириличної `А` | згортання омоглифів |
 *
 * ## Омоглифи — і чому в двох напрямках
 *
 * Тринадцять великих літер виглядають однаково в латиниці й кирилиці
 * (`ABCEHIKMOPTXY` / `АВСЕНІКМОРТХУ`). У школі перемикають розкладку постійно,
 * і «КАВА», набране латиницею, візуально не відрізнити від кириличної.
 *
 * Пароль складається з українських слів, тож для нього канонічна форма —
 * КИРИЛИЦЯ: латинські двійники згортаються в неї. Ідентифікатор складається з
 * латинських літер і цифр, тож для нього все навпаки. Це не дві різні
 * політики, а одна: «звести до алфавіту, у якому річ написана».
 */

/*
 * Алфавіт ідентифікатора — без `0`/`O`, `1`/`I`/`L`.
 *
 * Причина не в естетиці: ідентифікатор диктують уголос і переписують з екрана,
 * а нуль від літери «O» на екрані телефона в темряві залу не відрізняє ніхто.
 */
export const BOARD_ID_ALPHABET = '23456789ABCDEFGHJKMNPQRSTUVWXYZ';

/** Довжина ідентифікатора. П'ять розрядів — 28,6 млн варіантів. */
export const BOARD_ID_LENGTH = 5;

/** Скільки слів у згенерованому паролі. */
export const PASSWORD_WORD_COUNT = 3;

/** Скільки цифр у хвості згенерованого пароля. */
export const PASSWORD_DIGIT_COUNT = 4;

/**
 * Мінімальна довжина пароля, який людина вигадала САМА.
 *
 * Згенерований пароль довший і міцніший; це поріг для того випадку, коли його
 * замінили вручну. Він свідомо низький — це межа проти «1234», а не спроба
 * змусити когось вигадати сильний пароль. Запас від власного пароля залежить
 * лише від того, хто його вигадав, і саме тому інтерфейс попереджає про це
 * замість того, щоб мовчки вдавати, що всі паролі однакові.
 */
export const MIN_PASSWORD_LENGTH = 8;

/** Латинська → кирилиця. Ключі й значення — лише ВЕЛИКІ літери. */
const LATIN_TO_CYRILLIC: Readonly<Record<string, string>> = {
	A: 'А',
	B: 'В',
	C: 'С',
	E: 'Е',
	H: 'Н',
	I: 'І',
	K: 'К',
	M: 'М',
	O: 'О',
	P: 'Р',
	T: 'Т',
	X: 'Х',
	Y: 'У'
};

/** Кирилиця → латинська. Побудована з тієї самої таблиці, щоб не розійшлися. */
const CYRILLIC_TO_LATIN: Readonly<Record<string, string>> = Object.fromEntries(
	Object.entries(LATIN_TO_CYRILLIC).map(([latin, cyrillic]) => [cyrillic, latin])
);

/** NFC → верхній регістр → NFC ще раз: регістр здатен розкласти символ назад. */
const toUpperNfc = (raw: string): string => raw.normalize('NFC').toUpperCase().normalize('NFC');

/**
 * Нормалізація ідентифікатора: лише літери алфавіту, решта відкидається.
 *
 * Відкидається, а не замінюється: пробіл чи дефіс, які людина вставила для
 * зручності («AB-CDE»), не є частиною ідентифікатора.
 */
export function normalizeBoardId(raw: string): string {
	return [...toUpperNfc(raw)]
		.map((char) => CYRILLIC_TO_LATIN[char] ?? char)
		.filter((char) => BOARD_ID_ALPHABET.includes(char))
		.join('');
}

/**
 * Нормалізація пароля: слова через один дефіс, у верхньому регістрі.
 *
 * Розділювачем вважається будь-що, що не літера й не цифра, — саме тому
 * «КАВА ВІКНО», «КАВА-ВІКНО» і «КАВА  —  ВІКНО» дають один результат.
 */
export function normalizePassword(raw: string): string {
	const folded = [...toUpperNfc(raw)].map((char) => LATIN_TO_CYRILLIC[char] ?? char).join('');

	return folded.replace(/[^\p{L}\p{N}]+/gu, '-').replace(/^-+|-+$/g, '');
}

/**
 * Запас згенерованого пароля в бітах.
 *
 * Число НЕ вписане в прозу: воно рахується зі словника й констант, тож
 * схудлий словник або зменшена кількість слів роблять його меншим, а тест
 * (`secret.test.ts`) червоніє на порозі. Інакше запас лишився б твердженням у
 * коментарі, яке нічим не перевіряється.
 */
export function passwordEntropyBits(): number {
	return PASSWORD_WORD_COUNT * Math.log2(WORDS.length) + PASSWORD_DIGIT_COUNT * Math.log2(10);
}

/** Рівномірний вибір із масиву. `random` — щоб тест не залежав від випадку. */
function pick<T>(items: readonly T[], random: () => number): T {
	return items[Math.floor(random() * items.length)];
}

/**
 * Джерело випадковості за замовчуванням — криптографічне, а не `Math.random`.
 *
 * `Math.random` не призначений для секретів: його стан відновлюється зі
 * спостережених значень. Тут він лишається доступним ЛИШЕ як аргумент у
 * тестах, і саме тому типовий аргумент заданий тут, а не в місці виклику.
 */
export function cryptoRandom(): number {
	const buffer = new Uint32Array(1);
	globalThis.crypto.getRandomValues(buffer);
	return buffer[0] / 2 ** 32;
}

/** Згенерувати ідентифікатор дошки. */
export function makeBoardId(random: () => number = cryptoRandom): string {
	return Array.from({ length: BOARD_ID_LENGTH }, () => pick([...BOARD_ID_ALPHABET], random)).join(
		''
	);
}

/**
 * Згенерувати пароль: три слова й чотири цифри через дефіс.
 *
 * Слова МОЖУТЬ повторитися, і це навмисно: заборона повтору зменшила б
 * простір, а рахувати запас довелося б інакше. Виглядає повтор рідко (один
 * випадок на сто), і на диктування не впливає.
 */
export function makePassword(random: () => number = cryptoRandom): string {
	const words = Array.from({ length: PASSWORD_WORD_COUNT }, () => pick(WORDS, random));
	const digits = Array.from({ length: PASSWORD_DIGIT_COUNT }, () =>
		String(Math.floor(random() * 10))
	).join('');
	return [...words, digits].join('-');
}
