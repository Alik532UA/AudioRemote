import type { BoardInfo } from '$lib/net/boardTypes';

/**
 * СКІЛЬКИ ЖИВЕ ДОШКА, і хто її зрештою прибирає.
 *
 * ## Чого не було
 *
 * Покинуті дошки не прибирав НІХТО, і це записувалося як межа схеми: `boards`
 * не перелічується за побудовою (саме на цьому тримається пароль), а TTL у
 * Realtime Database не існує. Висновок звучав так: «автоматичного прибирання
 * тут не буде ніколи».
 *
 * Половина висновку хибна. Клієнтові справді не можна ні перелічити `boards`,
 * ні видалити чуже — і це лишається. Але СЕРВІСНИЙ АКАУНТ правила обходить
 * узагалі: для нього гілка перелічується, і саме він може прибрати те, чого не
 * знайде ніхто інший. Секрет `FIREBASE_SERVICE_ACCOUNT` у цьому репозиторії
 * уже заведений — ним викладаються правила.
 *
 * ## Три шари, і жодному не потрібно нових прав
 *
 *  1. **людина** — кнопка «видалити дошку» для своїх дощок. Була раніше;
 *  2. **господар** — свої ПРОСТРОЧЕНІ дошки, коли відкриває список
 *     (`expiredOwnBoards` нижче). Покриває найчастіший випадок: створив,
 *     закрив вкладку, повернувся через рік. Права ті самі, що й у кнопки;
 *  3. **прибиральний прогін** — усе інше, зокрема дошки тих, хто не
 *     повернеться ніколи (`scripts/sweep-boards.mjs`). Виконується сервісним
 *     акаунтом, без клієнта й без нових прав у когось.
 *
 * ## Чому вік рахується від `seenAt`, а не від `createdAt`
 *
 * Бо інакше дошка, яку відкривають щотижня третій рік, виглядала б
 * найстарішою з усіх. `seenAt` пише плеєр при відкритті — саме плеєр, бо це
 * «дошкою користуються», а не «хтось тримає відкритим пульт».
 *
 * `createdAt` лишається запасним: дошки, створені до появи `seenAt`, його не
 * мають, і прибирати їх найпотрібніше.
 */

/**
 * Скільки дошка живе після останнього відкриття.
 *
 * Пів року, і це не обережність заради обережності. Дошка тут — не сесія, а
 * інвентар залу: її створюють раз і диктують пароль колегам. Літні канікули в
 * школі тривають близько трьох місяців, тобто будь-яка межа коротша за них
 * зносила б робочі дошки до 1 вересня. Пів року дає запас навіть на рік, у
 * якому зал не працював семестр.
 *
 * Видалення незворотне: адресу дошки відновити неможливо за побудовою (вона
 * хеш від пари з паролем), тож помилка тут не має способу виправлення.
 */
export const BOARD_TTL_MS = 180 * 24 * 60 * 60 * 1000;

/** Коли дошкою користувалися востаннє. `0`, якщо невідомо взагалі. */
export function lastUsedAt(info: Pick<BoardInfo, 'createdAt' | 'seenAt'>): number {
	const seen = typeof info.seenAt === 'number' ? info.seenAt : 0;
	const created = typeof info.createdAt === 'number' ? info.createdAt : 0;
	return Math.max(seen, created);
}

/**
 * Чи дошку вже можна прибрати.
 *
 * Дошка без жодної позначки часу простроченою НЕ вважається. Це навмисно:
 * відсутність даних — не доказ віку, а найімовірніше ознака того, що запис
 * недописаний або схема змінилася. Незворотне видалення на такій підставі
 * робити не можна.
 */
export function isBoardExpired(
	info: Pick<BoardInfo, 'createdAt' | 'seenAt'>,
	now: number = Date.now()
): boolean {
	const used = lastUsedAt(info);
	if (used <= 0) return false;
	return now - used > BOARD_TTL_MS;
}
