const PORT = Number(process.env.PREVIEW_PORT ?? 4173);
const BASE = (process.env.BASE_PATH ?? '/AudioRemote').replace(/\/$/, '');

export default defineConfig({
	testDir: 'tests/e2e',
	/*
	 * `fullyParallel` і `forbidOnly` — звичайні. `retries` немає НАВМИСНО:
	 * перевірка, яка проходить із другого разу, тут нічого не доводить, а
	 * ховає рівно той клас дефектів, заради якого набір і зʼявився — гонки.
	 */
	fullyParallel: true,
	forbidOnly: !!process.env.CI,
	retries: 0,
	reporter: process.env.CI ? [['github'], ['list']] : [['list']],

	use: {
		/*
		 * КІНЦЕВА СКІСНА ТУТ ОБОВʼЯЗКОВА, а адреси в описах — відносні (`./menu`).
		 *
		 * `goto()` розвʼязує шлях через `new URL(path, baseURL)`, а провідна
		 * скісна в `path` за стандартом замінює ВЕСЬ шлях бази. Тобто
		 * `goto('/menu')` при базі `…/AudioRemote` іде на `localhost:4173/menu`
		 * — повз застосунок, на 404 сервера. Прогін при цьому не каже «база не
		 * та»: він просто не знаходить жодного елемента.
		 */
		baseURL: `http://localhost:${PORT}${BASE}/`,
		trace: 'retain-on-failure'
	},

	projects: [
		{ name: 'identity', testMatch: /identity\.setup\.ts$/ },
		{
			name: 'chromium',
			use: devices['Desktop Chrome'],
			dependencies: ['identity']
		}
	],

	webServer: {
		command: `node scripts/serve-build.mjs ${PORT}`,
		url: `http://localhost:${PORT}${BASE}/`,
		/*
		 * `reuseExistingServer` вимкнено й у CI, і локально. Чужий процес на
		 * тому самому порті — це рівно той випадок, який `identity` і ловить,
		 * але дешевше не пускати його взагалі, ніж ловити наслідки.
		 */
		reuseExistingServer: false,
		timeout: 30_000
	}
});
