import { defineConfig, devices } from '@playwright/test';

/**
 * БРАУЗЕРНІ ПЕРЕВІРКИ — НАД ЗІБРАНИМ АРТЕФАКТОМ, А НЕ НАД DEV-СЕРВЕРОМ.
 *
 * ## Навіщо вони тут узагалі
 *
 * Усе інше в цьому проєкті перевіряється або в `node`, або в jsdom, або
 * регулярками над джерелами. Три речі жодним із цих способів не видно, і всі
 * три вже ламалися:
 *
 *  * ПОЛІТИКА БЕЗПЕКИ. Хеш інлайн-скрипта звіряється текстом
 *    (`csp-hash.test.ts`), але чи пустив його БРАУЗЕР — питання іншого роду.
 *    Заблокований скрипт теми не дає ні помилки на екрані, ні падіння: лише
 *    мигання теми й рядок у консолі, якої ніхто не бачить.
 *  * СХЕМА КОЛЬОРІВ. `light-dark()` і `color-scheme` вирішує сам браузер.
 *    Саме тут і був дефект, описаний в `app.html`: атрибут теми міняється,
 *    сховище записане, а сторінка кольору не міняє.
 *  * РОЗКЛАДКА ХОСТИНГУ. `/{base}/menu` як `menu.html` і невідома адреса як
 *    `404.html` з кодом 404 — звички GitHub Pages, від яких залежить, чи
 *    відкриється застосунок і чи спрацює `+error.svelte`.
 *
 * ## Чому проєкт `identity` йде першим
 *
 * Бо найдорожча помилка браузерного набору — зелений прогін НЕ ПРОТИ ТОГО, що
 * перевіряли. Стара тека `build/`, дев-сервер на тому ж порті, чужий процес —
 * і набір чесно проходить, нічого не довівши (`GATE-E2E-IDENTITY`). Тому
 * перший проєкт доводить тотожність: версія, яку віддає порт, збігається з
 * версією в `package.json`, а в HTML є політика безпеки, якої в dev немає.
 * Решта проєктів залежать від нього й не стартують, доки він не пройшов.
 *
 * ## Межа набору
 *
 * Тут немає нічого, що вимагає ДОШКИ: бібліотека живе на диску того, хто грає,
 * а стан — у базі. Щоб дійти далі «оберіть папку», потрібна фікстура з
 * емулятором бази й підставним джерелом файлів; її ще немає, і в
 * `PROJECT-CONTEXT.md` § 5 це названо прямо.
 */

const PORT = Number(process.env.PREVIEW_PORT ?? 4173);
const BASE = (process.env.BASE_PATH ?? '/AudioRemote').replace(/\/$/, '');

/**
 * Другий сервер — DEV, і саме він говорить із емулятором бази.
 *
 * Конфіг Firebase запікається у збірку, тож набір з базою потребував би ВЛАСНОЇ
 * збірки — а в CI, де змінні вказують на бойову базу, переплутати дві теки
 * означало б писати пробними дошками у справжню базу школи. Dev-сервер бере
 * конфіг із `.env.development`, де прописано емулятор і нічого іншого бути не
 * може: помилитися нема чим.
 *
 * Базовий шлях у нього той самий, що в проді, — на одну розбіжність менше, і
 * заразом не доводиться передавати порожню змінну оточення, яку Windows
 * перетворює на відсутню.
 */
const DEV_PORT = Number(process.env.E2E_DEV_PORT ?? 5174);
const DB_PORT = Number(process.env.E2E_DB_PORT ?? 9020);

export default defineConfig({
	testDir: 'tests/e2e',
	/*
	 * `fullyParallel` і `forbidOnly` — звичайні. `retries` немає НАВМИСНО:
	 * перевірка, яка проходить із другого разу, тут нічого не доводить, а
	 * ховає рівно той клас дефектів, заради якого набір і зʼявився — гонки.
	 */
	fullyParallel: true,
	forbidOnly: !!process.env.CI,
	retries: 0,
	reporter: process.env.CI ? [['github'], ['list']] : [['list']],

	use: {
		/*
		 * КІНЦЕВА СКІСНА ТУТ ОБОВʼЯЗКОВА, а адреси в описах — відносні (`./menu`).
		 *
		 * `goto()` розвʼязує шлях через `new URL(path, baseURL)`, а провідна
		 * скісна в `path` за стандартом замінює ВЕСЬ шлях бази. Тобто
		 * `goto('/menu')` при базі `…/AudioRemote` іде на `localhost:4173/menu`
		 * — повз застосунок, на 404 сервера. Прогін при цьому не каже «база не
		 * та»: він просто не знаходить жодного елемента.
		 */
		baseURL: `http://localhost:${PORT}${BASE}/`,
		trace: 'retain-on-failure'
	},

	projects: [
		{ name: 'identity', testMatch: /identity\.setup\.ts$/ },
		{
			/*
			 * НАД АРТЕФАКТОМ: політика безпеки, базовий шлях, 404 — усе, що
			 * залежить від того, ЩО САМЕ поїде на хостинг.
			 */
			name: 'chromium',
			use: devices['Desktop Chrome'],
			testIgnore: /board\.spec\.ts$/,
			dependencies: ['identity']
		},
		{ name: 'emulator', testMatch: /board\.setup\.ts$/ },
		{
			/*
			 * НАД ПОВЕДІНКОЮ ДВОХ РОЛЕЙ: присутність, команди, квитанції, пароль
			 * у адресі дошки. Це домовленість між пристроями, і всередині одного
			 * процесу її не перевірити взагалі.
			 */
			name: 'board',
			use: {
				...devices['Desktop Chrome'],
				baseURL: `http://localhost:${DEV_PORT}${BASE}/`,
				/*
				 * Мова закріплена: типово Playwright дає `en-US`, і описи, писані
				 * українською, шукали б текст, якого на екрані немає. `uk-UA` —
				 * не підгонка, а основна мова інструменту: англійська тут запасна.
				 */
				locale: 'uk-UA'
			},
			testMatch: /board\.spec\.ts$/,
			dependencies: ['emulator'],
			/*
			 * ПОСЛІДОВНО Й З ДОВШОЮ МЕЖЕЮ, на відміну від решти набору.
			 *
			 * Кожен опис тут піднімає ДВА контексти браузера, і кожен з них
			 * компілюється dev-сервером на льоту та відкриває власний сокет до
			 * бази. Чотири такі пари одночасно впираються не в застосунок, а в
			 * перший компіл Vite — тобто червоне означало б «машина зайнята», а
			 * не «щось зламано». Плаваючий гейт гірший за відсутній.
			 */
			fullyParallel: false,
			timeout: 90_000
		}
	],

	webServer: [
		{
			command: `node scripts/serve-build.mjs ${PORT}`,
			url: `http://localhost:${PORT}${BASE}/`,
			/*
			 * `reuseExistingServer` вимкнено й у CI, і локально. Чужий процес на
			 * тому самому порті — це рівно той випадок, який `identity` і ловить,
			 * але дешевше не пускати його взагалі, ніж ловити наслідки.
			 */
			reuseExistingServer: false,
			timeout: 30_000
		},
		{
			/*
			 * ЕМУЛЯТОР ПЕРЕВИКОРИСТОВУЄТЬСЯ ЛОКАЛЬНО — і це протилежне рішення
			 * до сервера вище, бо питання інше. Там чужий процес підмінює те, що
			 * перевіряють; тут він і Є те, що потрібно, а піднімати другий однаково
			 * нікуди: порт один. У розробника емулятор часто вже висить із
			 * `npm run emulators`, і вимагати його зупинити означало б вимагати
			 * зупиняти роботу заради проби.
			 *
			 * У CI — завжди свій: там висіти нічому.
			 *
			 * Чи ТОЙ це емулятор, питає `board.setup.ts`: чужий, піднятий лише з
			 * `--only database`, виглядає як робочий, поки не дійде до входу.
			 */
			/*
			 * Команда НЕ дублюється, а береться зі скрипта проєкту: `npm run
			 * emulators` — це те саме, що розробник запускає руками щодня. Копія
			 * тут розійшлася б із оригіналом тихо (інший `--only`, інший проєкт),
			 * і набір би говорив не з тією базою.
			 */
			command: 'npm run emulators',
			port: DB_PORT,
			reuseExistingServer: !process.env.CI,
			timeout: 180_000
		},
		{
			command: `npx vite dev --port ${DEV_PORT} --strictPort`,
			port: DEV_PORT,
			env: { BASE_PATH: BASE },
			/*
			 * ПОРТ ТУТ СВІЙ (5174, а не 5173 у `npm run dev`) — щоб набір і робота
			 * не заважали одне одному.
			 *
			 * Пастка, яку варто знати: dev-сервер, що працював ДО `npm run build`,
			 * псується — збірка перегенеровує `.svelte-kit`, і він починає віддавати
			 * «Failed to fetch dynamically imported module». Заміряно: прогін одразу
			 * після збірки дав 11 описів із 15, і жоден не сказав, що винен сервер.
			 * У звичайному порядку («зібрати, потім прогнати») цього не буває:
			 * Playwright піднімає свій сервер уже після збірки.
			 *
			 * Вимикати перевикористання зовсім — гірше: зі `--strictPort` два
			 * прогони поспіль стикаються на порті, який ще не звільнився.
			 */
			reuseExistingServer: !process.env.CI,
			timeout: 120_000
		}
	]
});
