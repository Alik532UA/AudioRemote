import { sveltekit } from '@sveltejs/kit/vite';
import { defineConfig } from 'vitest/config';
import { VitePWA, type Display, type ManifestOptions } from 'vite-plugin-pwa';
import { readFileSync } from 'node:fs';

const pkg = JSON.parse(readFileSync('./package.json', 'utf-8'));

/*
 * У `vite.config.ts` доступний лише `process.env` — `$env` SvelteKit тут ще не
 * існує. Значення мусить збігатися з `svelte.config.js`: маніфест PWA описує
 * ту саму адресу, з якої віддається застосунок, і розбіжність тут дає
 * встановлений застосунок, який відкривається на чужому шляху.
 */
const isDev = process.argv.includes('dev');
const base = process.env.BASE_PATH ?? (isDev ? '' : '/AudioRemote');
const scope = base.endsWith('/') ? base : `${base}/`;

const manifest: Partial<ManifestOptions> = {
	name: 'AudioRemote',
	short_name: 'AudioRemote',
	description: 'Аудіодошка: один пристрій грає, інші ним керують',
	id: scope,
	scope,
	start_url: scope,
	display: 'standalone' as Display,
	background_color: '#181818',
	theme_color: '#222222',
	lang: 'uk',
	/*
	 * `any` В ОБОХ, і `maskable` тут БУЛО НЕПРАВДОЮ — заміряно, а не на око.
	 *
	 * `maskable` — це обіцянка з двох половин: (1) малюнок заповнює квадрат
	 * ЦІЛКОМ, бо система накладе на нього власну маску, і (2) весь істотний
	 * вміст лежить у центральному колі діаметром 80% сторони, бо решту маска
	 * має право обрізати.
	 *
	 * У `icon-192.png` не виконана ПЕРША половина, і не частково: по всьому
	 * периметру (768 пікселів) немає ЖОДНОГО непрозорого. Це готова іконка
	 * застосунку — сквіркл із помаранчевим градієнтом і прозорими кутами,
	 * 83.2% площі. Під маскою, ширшою за цей сквіркл, кути стають дірками, а
	 * під круглою виходить друге заокруглення поверх намальованого.
	 *
	 * Друга половина теж не виконана: радіус вмісту 110.4 при полі безпеки
	 * 76.8 (0.4 × 192).
	 *
	 * Невиконана обіцянка гірша за відсутню: без `maskable` система сама
	 * покладе значок на підкладку й додасть поле. Той самий висновок і з тієї
	 * самої причини вже записаний у сусідніх `HotPaste` і `MindStep`.
	 *
	 * Щоб повернути `maskable`, потрібен ІНШИЙ файл, а не інший рядок:
	 * суцільне тло на весь квадрат плюс логотип у центральних 80%.
	 */
	icons: [
		{ src: 'icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
		{ src: 'icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' }
	]
};

export default defineConfig({
	/*
	 * `base` тут НЕ задається: його виставляє SvelteKit із `paths.base`, і
	 * власне значення він однаково перекриє, надрукувавши попередження. Змінна
	 * `base` вище лишається — вона потрібна маніфесту PWA, який SvelteKit не
	 * чіпає, і виводиться з тієї самої `BASE_PATH`, тож розійтися їм нема з чого.
	 */
	define: {
		__APP_VERSION__: JSON.stringify(pkg.version)
	},
	plugins: [
		sveltekit(),
		VitePWA({
			filename: 'service-worker.js',
			/*
			 * `prompt`, а НЕ `autoUpdate`.
			 *
			 * `autoUpdate` разом зі `skipWaiting` означає, що новий воркер
			 * забирає вже відкриту вкладку під себе, а `cleanupOutdatedCaches`
			 * прибирає з передкешу старі чанки. У звичайному застосунку це
			 * коштує втраченого стану сторінки. ТУТ це коштує більшого:
			 * вкладка-приймач — єдине, що грає звук, і перезавантаження посеред
			 * відтворення глушить зал. Причому рішення про це ухвалив би воркер,
			 * а не людина.
			 *
			 * Із `prompt` новий воркер стоїть у `waiting`, людина бачить
			 * пропозицію й застосовує її тоді, коли зал порожній
			 * (VERSIONING-v9 § 4.5, `VER-OPEN-TAB-SURVIVES`).
			 *
			 * Інваріант тримає `scripts/check-build.mjs`: він читає ЗІБРАНИЙ
			 * `service-worker.js` і червоніє, якщо генератор усе-таки вставив
			 * `skipWaiting()`. Перевіряти джерело тут недостатньо — прапорець
			 * приходить із конфігу плагіна, а не з нашого коду.
			 */
			registerType: 'prompt',
			manifest,
			injectRegister: false,
			workbox: {
				cleanupOutdatedCaches: true,
				globPatterns: isDev ? [] : ['**/*.{js,css,html,ico,png,svg,webp,woff2,json}'],
				/*
				 * Той самий файл, що й `fallback` в адаптері: офлайн-воркер мусить
				 * віддавати рівно ту оболонку, яку віддав би сервер.
				 */
				navigateFallback: isDev ? null : `${scope}404.html`,
				dontCacheBustURLsMatching: /-[a-f0-9]{8}\./
			},
			devOptions: {
				enabled: false,
				suppressWarnings: true,
				type: 'module'
			}
		})
	],
	build: {
		sourcemap: true
	},
	/*
	 * УМОВИ РОЗВʼЯЗАННЯ — БРАУЗЕРНІ, І ЛИШЕ ПІД VITEST.
	 *
	 * `mount()` зі svelte існує у двох виданнях: клієнтському й серверному.
	 * Типово node бере серверне, і компонентна перевірка падає з
	 * `mount(...) is not available on the server` — тобто з повідомленням про
	 * сервер там, де ніякого сервера немає (застосунок статичний, `ssr = false`).
	 *
	 * Прапорець `process.env.VITEST` тримає це виключно в перевірках: збірка
	 * умов не міняє, і сплутати їх нема з чим.
	 */
	resolve: process.env.VITEST ? { conditions: ['browser'] } : undefined,
	test: {
		/*
		 * І `.spec.ts`, і `.test.ts`. Конвенція проєкту — `.test.ts`, але файл
		 * із «неправильним» суфіксом просто не запускався б, і ніщо б про це не
		 * сказало: vitest звітує успіх, не подивившись на нього
		 * (AI-AGENT-PITFALLS-v9 § 1.3).
		 */
		include: ['src/**/*.{spec,test}.ts'],
		/*
		 * `node`, а не `jsdom`, — типово. Майже вся логіка тут чиста, а jsdom
		 * НЕ реалізує `crypto.subtle`: під ним виведення адреси дошки падало б
		 * не через помилку в коді, а через середовище. Файли, яким потрібен
		 * DOM, оголошують це самі рядком `// @vitest-environment jsdom`.
		 */
		environment: 'node',
		/*
		 * ПОКРИТТЯ — ПІДЛОГА, А НЕ МЕТА (CODE-QUALITY-v9 § 6.2).
		 *
		 * ## Що це число доводить, а що ні
		 *
		 * Воно НЕ доводить, що логіка перевірена: рядок, який виконався під час
		 * прогону, зарахований навіть тоді, коли про його результат ніхто не
		 * питав. Тому канонічної цілі «70%» тут немає й гнатися за нею не
		 * будемо — це найдешевший спосіб написати перевірки, які нічого не
		 * перевіряють (§ 3.5).
		 *
		 * Доводить воно інше, і саме заради цього стоїть: що перевірок не
		 * СТАЛО МЕНШЕ. Видалений файл перевірок, модуль, який вирішили не
		 * покривати взагалі, цілий шар, що приїхав без жодного опису, — усе це
		 * видно тут і більше ніде: `npm test` лишається зеленим, бо він міряє
		 * те, що є, а не те, чого немає.
		 *
		 * ## Чому окремим скриптом, а не в `npm test`
		 *
		 * Інструментування додає до прогону вісім секунд при десяти. `npm test`
		 * тут запускають десятки разів на день, а покриття змінюється рівно
		 * тоді, коли міняється склад перевірок. Тому воно стоїть у CI окремим
		 * кроком, як `check:bundle` і `check:build`, а те, що крок не зник із
		 * воркфлоу, стереже `src/ci.test.ts`.
		 *
		 * ## Звідки числа
		 *
		 * Заміряно на 589 перевірках: 51.06 / 48.05 / 49.92 / 52.34. Пороги —
		 * на пункт нижче: локальний прогін іде на node 25, CI на node 22, а
		 * дрібний розкид у підрахунку гілок між версіями V8 дорожчий за пункт
		 * суворості (та сама причина, що й допуск у `check:bundle`,
		 * `CI-BUDGET-TOLERANCE`).
		 *
		 * ЧИСЛО ЛИШЕ РОСТЕ. Опустити його можна рівно з одного приводу:
		 * перевірки видалили навмисно, і в коміті сказано, чому.
		 *
		 * І росте воно РАЗОМ із перевірками, а не колись потім. Поріг, що
		 * відстав на два пункти, мовчки дозволяє видалити рівно стільки ж —
		 * тобто перестає бути тим єдиним, що він міряє. Те саме число стоїть у
		 * PROJECT-CONTEXT § 6 і звіряється звідси (`docs-facts`).
		 *
		 * ## Чому лише `.ts`
		 *
		 * Компонентна перевірка тут поки одна (`VerdictToast.test.ts`), і
		 * покритих компонентів один із півсотні. Узяти `.svelte` в цей самий
		 * поріг означало б обвалити його до двох відсотків, тобто розмити
		 * єдине число, яке зараз щось міряє; завести окремий поріг на два
		 * відсотки — записати шум. Другий поріг зʼявиться тоді, коли
		 * компонентних перевірок стане достатньо, щоб його падіння щось
		 * означало.
		 */
		coverage: {
			provider: 'v8',
			include: ['src/lib/**/*.ts'],
			exclude: ['**/*.test.ts', '**/*.d.ts'],
			reporter: ['text-summary'],
			thresholds: { statements: 50, branches: 47, functions: 48, lines: 51 }
		}
	}
});
